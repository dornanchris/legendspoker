# Count Dracula's clips: writes web/art/dracula/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/dracula_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/dracula/'
K = ROOT + 'art-tools/dracula_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One long black nail taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A hand cupped low over his cards, eyes down.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A flat hand slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a hand pushed well forward, unhurried.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Pushes forward along the felt, leaning in, a cold smile.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A hand turns palm up (the game turns the cards).')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A bored flick of the fingers toward the middle.')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: both hands raised and spread, fangs bared.', lead=-2)
C['arrive'] = frame('arrive', 2.2, 0.0, 1.8, 'BEAT: played as he sits down: sweeping his cape back as he takes the chair.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, a long hand raised, palm open. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: sits back, looking down his nose.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a thin, cold smile, eyes narrowed.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: a snarl, fangs bared, nails gouging the felt.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, red eyes level.', lead=3)
C['laugh'] = frame('laugh', 2.0, 0.2, 1.6, 'BEAT: a low laugh, head tipped back, fangs showing.')
C['eyebrow'] = frame('eyebrow', 2.4, 0.22, 2.0, 'TELL: raises one eyebrow.', lead=0)
C['smile'] = frame('smile', 2.4, 0.22, 2.0, 'IDLE (decoy for the eyebrow): smiles without showing his teeth.', lead=0)
C['sip'] = frame('sip', 2.4, 0.22, 2.0, 'TELL AND IDLE, the same drawing: sips from his chalice.', lead=0)
C['steeple'] = frame('steeple', 2.4, 0.22, 2.0, 'TELL: steeples his fingers.')
C['fingernail'] = frame('fingernail', 2.4, 0.22, 2.0, 'IDLE (decoy for the steeple): runs a fingernail along the table.')
C['pulse'] = frame('pulse', 2.4, 0.22, 2.0, "IDLE: watches the pulse in someone's throat.", lead=0)
C['turn'] = frame('turn', 2.0, 0.2, 1.6, 'IDLE: turns to look at you, a polite smile.', lead=0)
C['swirl'] = frame('swirl', 2.4, 0.22, 2.0, 'IDLE: swirls the wine in his chalice.', lead=0)
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.15], ['down', 0.25]]
face['gaze']['tilt'] = {k: v for k, v in face['gaze']['tilt'].items() if k in ('ahead', 'down', 'viewer', 'narrow')}
a = {'note': "Hand-authored: Count Dracula's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'raises one eyebrow': 'eyebrow', 'sips from his chalice': 'sip', 'steeples his fingers': 'steeple',
              'runs a fingernail along the table': 'fingernail', 'smiles without showing his teeth': 'smile',
              "watches the pulse in someone's throat": 'pulse'},
     'fidgets': ['turn', 'swirl']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

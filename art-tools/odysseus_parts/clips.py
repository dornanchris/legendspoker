# odysseus's clips: writes web/art/odysseus/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/odysseus_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/odysseus/'
K = ROOT + 'art-tools/odysseus_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
rose = json.load(open(ROOT + 'web/art/roosevelt/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards, eyes down (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.6, 0.2, 1.2, 'Sets a taller stack down well forward.')
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Slides his cards away.')
C['all_in'] = frame('all_in', 2.0, 0.22, 1.6, 'Pushes his whole stack in, a calm half-smile.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Draws the pot in with both hands.')
C['twist'] = frame('twist', 2.2, 0.22, 1.8, 'TELL: twists the ring on his finger.', lead=1)
C['admire'] = frame('admire', 2.2, 0.22, 1.8, 'IDLE (decoy for the twist): rubs his thumb over the ring, admiring it.', lead=1)
C['door'] = frame('door', 2.4, 0.25, 2.0, 'TELL: looks toward the door, as if it led home.', lead=0.5)
C['exits'] = frame('exits', 2.4, 0.25, 2.0, 'IDLE (decoy for the door): counts the exits.', lead=0.5)
C['lean_back'] = frame('lean_back', 2.6, 0.3, 2.2, 'TELL: leans back, satisfied.', lead=-2)
C['stretch'] = frame('stretch', 2.4, 0.3, 2.0, 'IDLE (decoy for leaning back): stretches his back.', lead=-2)
C['wring'] = frame('wring', 2.4, 0.25, 2.0, 'IDLE: wrings sea water from the hem of his cloak.')
C['scar'] = frame('scar', 2.2, 0.25, 1.8, 'IDLE: rubs an old scar on his thigh, under the table.', lead=1.5)
C['smile'] = frame('smile', 2.0, 0.22, 1.6, 'IDLE: smiles at no one in particular.', lead=0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: spinning a story, one hand open. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: brows up, doing sums.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.25, 1.8, 'BEAT: lost a pot: a rueful smile, a hand raised: fair enough.')
C['won_pot'] = frame('won_pot', 2.0, 0.22, 1.6, 'BEAT: won a pot: a sly grin and a wink.')
C['arrive'] = frame('arrive', 3.0, 0.05, 2.6, 'BEAT: just arrived, soaking wet and apologising.', lead=-1)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: rises, setting his cap straight for the road home.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(rose['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['down', 0.14], ['viewer', 0.12], ['side', 0.14]]
face['gaze']['tilt'].pop('up', None)
face['gaze']['tilt']['side'] = [-0.6, 0, 0]
a = {'note': "Hand-authored: Odysseus's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'twists the ring on his finger': 'twist', 'looks toward the door as if it led home': 'door',
              'leans back, satisfied': 'lean_back', 'wrings sea water from the hem of his cloak': 'wring',
              'counts the exits': 'exits', 'rubs an old scar on his thigh': 'scar', 'smiles at no one in particular': 'smile'},
     'fidgets': ['admire', 'stretch', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# nemo's clips: writes web/art/nemo/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/nemo_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/nemo/'
K = ROOT + 'art-tools/nemo_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two knuckles rap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward.')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Sets a stack down, precise.', lead=1.5)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Lays his cards down, disdainful.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push his whole stack in, grim.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['listen'] = frame('listen', 2.6, 0.25, 2.2, 'TELL: closes his eyes, as if listening to distant music.', lead=-0.5)
C['fugue'] = frame('fugue', 2.4, 0.22, 2.0, 'IDLE (decoy for the eyes closed): hums a fugue under his breath, keeping time.', lead=-0.3)
C['window'] = frame('window', 2.4, 0.22, 2.0, 'TELL: lets his gaze drift to the window.', lead=-0.3)
C['chronometer'] = frame('chronometer', 2.2, 0.2, 1.8, 'IDLE (decoy for the window): consults a pocket chronometer.')
C['pearl'] = frame('pearl', 2.4, 0.22, 2.0, 'TELL: turns the great pearl between his fingers.')
C['hull'] = frame('hull', 2.0, 0.18, 1.6, 'IDLE (decoy for the pearl): taps the table as if sounding a hull.', lead=0.5)
C['notebook'] = frame('notebook', 2.8, 0.25, 2.4, 'IDLE: sketches something in a notebook.', lead=0.5)
C['cold_look'] = frame('cold_look', 2.2, 0.2, 1.8, 'IDLE: a cold, level look at the player.')
C['arms_folded'] = frame('arms_folded', 2.8, 0.25, 2.4, 'IDLE: arms folded on the table, brooding.', lead=0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a flat hand raised, final. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: brows drawn, a long cold stare.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: jaw set, eyes lowered.')
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a grave half-smile, drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, eyes hard.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: rises, pockets the pearl, turns away without a word.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.62], ['viewer', 0.12], ['down', 0.14], ['side', 0.12]]
a = {'note': "Hand-authored: Nemo's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'closes his eyes, as if listening to distant music': 'listen',
              'lets his gaze drift to the window': 'window',
              'turns a pearl between his fingers': 'pearl',
              'consults a pocket chronometer': 'chronometer',
              'hums a fugue under his breath': 'fugue',
              'sketches something in a notebook': 'notebook',
              'taps the table as if sounding a hull': 'hull'},
     'fidgets': ['cold_look', 'arms_folded', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

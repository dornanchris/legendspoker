# kidd's clips: writes web/art/kidd/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/kidd_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/kidd/'
K = ROOT + 'art-tools/kidd_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
rose = json.load(open(ROOT + 'web/art/roosevelt/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards, eyes down (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.7, 0.2, 1.3, 'Pushes a huge stack far forward with both hands, greedy.', lead=3)
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Pushes his cards away, aggrieved.')
C['all_in'] = frame('all_in', 2.0, 0.22, 1.6, 'Shoves his whole stack in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Wraps both arms round the pot and draws it close.')
C['pat'] = frame('pat', 2.0, 0.22, 1.6, 'TELL: pats his coat where a map might be.', lead=1)
C['straighten'] = frame('straighten', 2.0, 0.22, 1.6, 'IDLE (decoy for the pat): straightens the front of his coat.', lead=1)
C['chew'] = frame('chew', 2.2, 0.25, 1.8, 'TELL: chews his lip.', lead=0.5)
C['cravat'] = frame('cravat', 2.2, 0.22, 1.8, 'IDLE (decoy for the lip): loosens his cravat.', lead=0.5)
C['glance'] = frame('glance', 2.0, 0.2, 1.6, 'TELL: glances over his shoulder.', lead=-1)
C['squint'] = frame('squint', 2.2, 0.22, 1.8, 'IDLE (decoy for the glance): squints at the lamp.', lead=-1)
C['neck'] = frame('neck', 2.2, 0.22, 1.8, 'IDLE: rubs his neck, tired.')
C['count'] = frame('count', 2.6, 0.25, 2.2, "IDLE: counts coins that aren't there.", lead=1)
C['hat_tip'] = frame('hat_tip', 1.8, 0.2, 1.4, 'IDLE: tips his hat to the room.', lead=-1)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a finger raised, protesting his case. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: a greedy, calculating look.')
C['lost_pot'] = frame('lost_pot', 2.0, 0.18, 1.6, 'BEAT: lost a pot: both palms up, this is robbery.', lead=-1)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a relieved, greedy grin, hands on his chips.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, anxious and fixed.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: rises, holding out his papers, protesting.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(rose['face']))
face['gaze']['idle'] = [['ahead', 0.62], ['down', 0.16], ['viewer', 0.12], ['side', 0.1]]
face['gaze']['tilt'].pop('up', None)
face['gaze']['tilt']['narrow'] = [0.8, 0, 0.5]
face['gaze']['tilt']['side'] = [-0.6, 0, 0]
a = {'note': "Hand-authored: Kidd's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'pats his coat where a map might be': 'pat', 'chews his lip': 'chew', 'glances over his shoulder': 'glance',
              'rubs his neck': 'neck', "counts coins that aren't there": 'count', 'tips his hat to the room': 'hat_tip',
              'squints at the lamp': 'squint'},
     'fidgets': ['straighten', 'cravat', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

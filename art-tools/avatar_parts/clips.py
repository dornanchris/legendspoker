# The Stranger (the player, seen once at the finale; later online): writes web/art/stranger/anim.json (face timing, clips,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/avatar_parts/clips.py
# NO tells (rule 3): it acts out only what the player did, and sheet C's loops
# are fidgets. No face: a shadow under the hat, so no blink, no mouth; it nods.
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/stranger/'
K = ROOT + 'art-tools/avatar_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
dealer = json.load(open(ROOT + 'web/art/death/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A gloved hand cupped low over the cards, the hat brim bowed.')
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['call'] = frame('call', 1.5, 0.18, 1.15, "A flat hand slides forward along the felt (the chips are the game's).")
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a hand pushed well forward.')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A small push of the hand toward the middle.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push forward along the felt, leaning in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A hand turns palm up (the game turns the cards).')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: both fists raised, the hat tipped back.', lead=-2)
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: the hat brim pulled down, head bowed.')
C['lost_pot'] = frame('lost_pot', 2.0, 0.2, 1.6, 'BEAT: lost a pot: leans back, settling in.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms.', lead=3)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, a hand raised, palm open.')
C['tip'] = frame('tip', 2.4, 0.22, 2.0, 'LOOP: tips the brim of the hat.', lead=0)
C['scarf'] = frame('scarf', 2.4, 0.22, 2.0, 'LOOP: settles the scarf at the collar.', lead=0)
C['settle'] = frame('settle', 2.0, 0.2, 1.6, 'LOOP: leans back, settling in.', lead=0)
C['collar'] = frame('collar', 2.4, 0.22, 2.0, 'LOOP: turns the coat collar up.', lead=0)
C['glove'] = frame('glove', 2.4, 0.22, 2.0, 'LOOP: pulls a glove snug at the wrist.', lead=0)
C['glance'] = frame('glance', 2.4, 0.22, 2.0, 'LOOP: glances round the room.', lead=0)
face = json.loads(json.dumps(dealer['face']))      # no face: no blink, eyes ahead
face['speech'] = json.load(open(ROOT + 'web/art/green_knight/anim.json'))['face']['speech']   # it talks with a nod, as the helm does
a = {'note': "Hand-authored: the Stranger, the player's own figure (the finale's left-hand chair; later the default online avatar). "
             "No tells (rule 3): its loops are fidgets only. rig.json and the images beside it are generated by art-tools/pose_rig.py; "
             "`accent` by art-tools/avatar_parts/accent_masks.py.",
     'avatar': True, 'face': face, 'clips': C, 'cues': {},
     'fidgets': ['tip', 'scarf', 'settle', 'collar', 'glove', 'glance']}
old = json.load(open(R + 'anim.json')) if os.path.exists(R + 'anim.json') else {}
if 'accent' in old: a['accent'] = old['accent']
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# The Martian's clips: writes web/art/martian/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/martian_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/martian/'
K = ROOT + 'art-tools/martian_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two tentacle-tips tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Tentacle-tips curled low over its cards, eyes down.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A bunch of tentacles slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'The great head leans forward, a bunch of tentacles pushed well forward.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both bunches push forward together, the head leaning in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Tentacle-tips turn over (the game turns the cards).')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A dismissive flick of a bunch of tentacles.')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: both bunches raised high and writhing, beak wide.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, hooting, a bunch of tentacles lifted. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: head drawn back, eyes wide.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: head sagging, eyes half shut.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: tentacles thrashing on the felt, beak wide in a howl.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: the head leaning far forward, tentacles stretched.', lead=3)
C['laugh'] = frame('laugh', 2.0, 0.2, 1.6, 'BEAT: a low hooting laugh, tentacles rippling.')
C['curl'] = frame('curl', 2.4, 0.22, 2.0, 'TELL: its tentacles curl up tight.', lead=0)
C['drum'] = frame('drum', 2.2, 0.22, 1.8, 'IDLE (decoy for the curl): drums three tentacles in sequence.')
C['count'] = frame('count', 2.4, 0.22, 2.0, 'TELL: works something out on its tentacle-tips.')
C['blink_odd'] = frame('blink_odd', 2.0, 0.22, 1.6, 'TELL: its great eyes blink out of time with each other.', lead=0)
C['colour'] = frame('colour', 2.4, 0.22, 2.0, 'IDLE: its skin shifts colour, faintly.', lead=0)
C['breathe'] = frame('breathe', 2.4, 0.22, 2.0, 'IDLE: breathes heavily in the heavy air.', lead=0)
C['earth'] = frame('earth', 2.4, 0.2, 2.0, 'IDLE (decoy for the blink): looks down at Earth through the window.', lead=0)
C['turn'] = frame('turn', 2.0, 0.2, 1.6, 'IDLE: turns its head to look at you.', lead=0)
C['sag'] = frame('sag', 2.4, 0.22, 2.0, 'IDLE: sags in its seat under Earth\'s gravity.', lead=0)
face = json.loads(json.dumps(kidd['face']))
face['blink'] = {'every': [3.5, 7.5], 'double': 0, 'frames': [['half', 0.06], ['closed', 0.09], ['half', 0.06]]}
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.15], ['down', 0.25]]
face['gaze']['tilt'] = {k: v for k, v in face['gaze']['tilt'].items() if k in ('ahead', 'down', 'viewer', 'narrow')}
a = {'note': "Hand-authored: the Martian's face timing and its clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'its tentacles curl': 'curl', 'its great eyes blink out of time with each other': 'blink_odd',
              'works something out on its tentacle-tips': 'count', 'drums three tentacles in sequence': 'drum',
              'its skin shifts colour, faintly': 'colour', 'breathes heavily in the heavy air': 'breathe',
              'looks down at Earth through the window': 'earth'},
     'fidgets': ['turn', 'sag']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

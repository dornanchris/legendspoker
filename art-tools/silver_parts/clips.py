# silver's clips: writes web/art/silver/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/silver_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/silver/'
K = ROOT + 'art-tools/silver_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far', 'parrot']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.7, 0.2, 1.3, 'Sets a tall stack down, smiling.', lead=2)
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Slides his cards away, cheerful.')
C['all_in'] = frame('all_in', 2.0, 0.22, 1.6, 'Pushes his whole stack in with both hands.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['squawk'] = frame('squawk', 1.8, 0.15, 1.4, "TELL: the parrot squawks 'Pieces of eight!', wings half open.", lead=0.5)
C['preen'] = frame('preen', 2.2, 0.2, 1.8, 'IDLE (decoy for the squawk): the parrot preens under a wing.', lead=0.5)
C['sidle'] = frame('sidle', 2.0, 0.2, 1.6, 'TELL: the parrot sidles along his shoulder toward his ear.', lead=0.5)
C['flap'] = frame('flap', 1.6, 0.12, 1.2, 'IDLE (decoy for the sidle): the parrot flaps once and settles.', lead=0.5)
C['stroke'] = frame('stroke', 2.2, 0.22, 1.8, "TELL: strokes the parrot's head with one finger.", lead=-1)
C['apron'] = frame('apron', 2.2, 0.22, 1.8, 'IDLE (decoy for the stroke): wipes his hands on his apron.', lead=1)
C['grin_round'] = frame('grin_round', 2.0, 0.2, 1.6, 'IDLE: grins at everyone at once.')
C['crutch'] = frame('crutch', 1.8, 0.2, 1.4, 'IDLE: raps his crutch with his knuckles.')
C['chin'] = frame('chin', 2.6, 0.25, 2.2, 'IDLE: leans an elbow on the table, chin in hand, friendly.', lead=1)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: one hand open, spinning a yarn. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: eyes narrowed, still smiling.')
C['lost_pot'] = frame('lost_pot', 2.0, 0.18, 1.6, 'BEAT: lost a pot: a broad, easy laugh, palms up.', lead=-1)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a wink, drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on his forearm, the smile gone cold.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: two fingers to his brow, a salute.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.18], ['down', 0.12], ['side', 0.1]]
a = {'note': "Hand-authored: Silver's face timing and his clips (poker actions, the parrot's tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {"his parrot squawks 'Pieces of eight!'": 'squawk', 'his parrot sidles along his shoulder': 'sidle',
              "strokes the parrot's head": 'stroke', 'the parrot preens': 'preen', 'grins at everyone at once': 'grin_round',
              'raps his crutch against the table leg': 'crutch', 'wipes his hands on his apron': 'apron'},
     'fidgets': ['flap', 'chin', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# The Phoenix's clips: writes web/art/phoenix/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/phoenix_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/phoenix/'
K = ROOT + 'art-tools/phoenix_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'A wingtip taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A wingtip cupped low over its cards, head bent to look.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A wingtip slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a wingtip pushed well forward.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both wings sweep forward together, the crest blazing.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A wingtip turns over (the game turns the cards).')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A small, dismissive flick of a wingtip.')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: wings spread high, crest blazing, a triumphant cry.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a trill, beak a little open (Death translates). Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: feathers sleeked flat, perfectly still.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: feathers ruffled, head tucked a little.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: head bowed, wings drooping, ash falling.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: heads up: leaning in, both wingtips forward on the felt.', lead=3)
C['knocked_out'] = frame('knocked_out', 3.0, 0.25, 2.8, 'BEAT: knocked out: burns down all at once in a great bright flame.', lead=0)
C['spread'] = frame('spread', 2.6, 0.25, 2.2, 'IDLE: spreads its wings wide, lighting the room (its heads-up opener).', lead=0)
C['sing'] = frame('sing', 2.4, 0.22, 2.0, 'IDLE: sings one clear note.', lead=0)
C['flare'] = frame('flare', 2.4, 0.22, 2.0, 'TELL: the flames along its crest flare up.', lead=0)
C['spark'] = frame('spark', 2.4, 0.22, 2.0, 'IDLE (decoy for the flare): a spark drifts up from its crest.', lead=0)
C['preen'] = frame('preen', 2.4, 0.22, 2.0, 'TELL: preens one wing, unhurried.')
C['ash'] = frame('ash', 2.4, 0.22, 2.0, 'IDLE (decoy for the preen): shakes a little ash from its feathers.')
C['embers'] = frame('embers', 2.4, 0.22, 2.0, 'TELL: its feathers dim to embers.', lead=0)
C['light'] = frame('light', 2.4, 0.22, 2.0, 'IDLE (decoy for the embers): turns its head toward the light.', lead=0)
C['eye'] = frame('eye', 2.4, 0.22, 2.0, 'IDLE: watches you with one gold eye.', lead=0)
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.7], ['down', 0.15], ['side', 0.15]]
face['gaze']['tilt'] = {k: v for k, v in face['gaze']['tilt'].items() if k in ('ahead', 'down', 'side')}
a = {'note': "Hand-authored: the Phoenix's face timing and its clips (poker actions, tells beside their decoys, beats). "
             "It does not speak (Death translates): its beak opens on a trill when it has a line. "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'the flames along its crest flare up': 'flare', 'preens one wing, unhurried': 'preen',
              'its feathers dim to embers': 'embers', 'a spark drifts up from its crest': 'spark',
              'shakes a little ash from its feathers': 'ash', 'turns its head toward the light': 'light',
              'watches you with one gold eye': 'eye'},
     'fidgets': ['sing', 'spread']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

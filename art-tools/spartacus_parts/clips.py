# spartacus's clips: writes web/art/spartacus/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/spartacus_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/spartacus/'
K = ROOT + 'art-tools/spartacus_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Knuckles rap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.5, 0.12, 1.1, 'Shoves a stack forward, hard.', lead=2)
C['fold'] = frame('fold', 1.2, 0.15, 0.85, 'Flicks his cards away.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands drive his whole stack forward.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms drag the pot in.')
C['shoulders'] = frame('shoulders', 2.2, 0.2, 1.8, 'TELL: rolls his shoulders like a fighter before a bout.', lead=-0.5)
C['neck'] = frame('neck', 2.2, 0.2, 1.8, 'IDLE (decoy for the shoulders): rolls his neck.', lead=-0.3)
C['scar'] = frame('scar', 2.4, 0.22, 2.0, 'TELL: rubs the old shackle scar on his wrist.', lead=0.5)
C['flex'] = frame('flex', 2.0, 0.2, 1.6, 'IDLE (decoy for the scar): flexes his hands, fingers spread.', lead=0.5)
C['stare'] = frame('stare', 2.4, 0.22, 2.0, 'TELL: stares hard across the table.', lead=0.5)
C['doors'] = frame('doors', 2.2, 0.2, 1.8, 'IDLE (decoy for the stare): glances at the doors.')
C['table_weight'] = frame('table_weight', 2.4, 0.22, 2.0, "IDLE: grips the table's edge as if testing its weight.", lead=1)
C['laugh'] = frame('laugh', 1.8, 0.15, 1.4, 'IDLE: a short, hard laugh.', lead=-0.5)
C['arms_folded'] = frame('arms_folded', 2.8, 0.25, 2.4, 'IDLE: arms folded on the table, watching.', lead=0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: one fist on the table, blunt. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: jaw set, leaning in.', lead=1.5)
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a hard exhale, head tilted back.', lead=-0.5)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a fierce grin, dragging the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning over the table on both fists.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: stands, looks once at the doors, and goes.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.14], ['down', 0.1], ['side', 0.16]]
a = {'note': "Hand-authored: Spartacus's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'rolls his shoulders like a fighter before a bout': 'shoulders',
              'rubs the old shackle scar on his wrist': 'scar',
              'stares hard across the table': 'stare',
              'flexes his hands': 'flex',
              'tests the weight of the table as if it might be a weapon': 'table_weight',
              'glances at the doors': 'doors',
              'rolls his neck': 'neck'},
     'fidgets': ['laugh', 'arms_folded', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

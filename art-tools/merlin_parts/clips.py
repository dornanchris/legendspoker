# merlin's clips: writes web/art/merlin/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/merlin_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/merlin/'
K = ROOT + 'art-tools/merlin_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far', 'staff']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.8, 0.25, 1.4, 'Sets a stack down, slow and deliberate.', lead=1)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Slides his cards away without looking at them.')
C['all_in'] = frame('all_in', 2.2, 0.3, 1.8, 'Pushes his whole stack in with both hands, calm.', lead=2)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in, unhurried.')
C['glow'] = frame('glow', 2.4, 0.25, 2.0, 'TELL: his staff hums, faintly: a soft light along it. He does not touch it.', lead=0.3)
C['tap'] = frame('tap', 1.8, 0.2, 1.4, 'IDLE (decoy for the glow): taps his staff twice.', lead=0.5)
C['gaze'] = frame('gaze', 2.6, 0.25, 2.2, 'TELL: gazes somewhere past the table, as if the hand were already over.', lead=0.3)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: his right hand raised, palm out, a quiet prophecy. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.4, 0.25, 2.0, 'BEAT: facing a big bet: eyes narrowed, unmoved.', lead=0.5)
C['lost_pot'] = frame('lost_pot', 2.2, 0.22, 1.8, 'BEAT: lost a pot: a small nod, as if he expected it.', lead=1)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a faint knowing smile, drawing the chips in.', lead=1)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: hands clasped on the table, the deep eyes fixed.', lead=2)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: takes up his staff and turns to go, unhurried.', lead=-2)
C['stare'] = frame('stare', 2.4, 0.25, 2.0, 'IDLE (decoy for the gaze): stares at something that has not happened yet.', lead=-0.5)
C['murmur'] = frame('murmur', 2.2, 0.22, 1.8, 'TELL: murmurs a word nobody catches.', lead=0.5)
C['beard'] = frame('beard', 2.4, 0.22, 2.0, 'IDLE (decoy for the murmur): strokes his beard.', lead=0.5)
C['ash'] = frame('ash', 2.2, 0.22, 1.8, 'IDLE: brushes ash from his sleeve.', lead=0.5)
C['candle'] = frame('candle', 2.4, 0.25, 2.0, 'IDLE: the candle nearest him bends the wrong way: he glances up at it, one finger lifted (the room gutters it).', lead=-0.5)
C['still'] = frame('still', 3.0, 0.3, 2.6, 'IDLE: hands folded, eyes closed, perfectly still.', lead=0.5)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['far', 0.16], ['down', 0.14], ['viewer', 0.1]]
face['gaze']['tilt'].pop('narrow', None); face['gaze']['tilt']['far'] = [-0.4, 0, 0]
a = {'note': "Hand-authored: Merlin's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'his staff hums, faintly': 'glow', 'gazes somewhere past the table, as if the hand were already over': 'gaze',
              'murmurs a word nobody catches': 'murmur', 'the candle nearest him bends the wrong way': 'candle',
              'stares at something that has not happened yet': 'stare', 'brushes ash from his sleeve': 'ash',
              'taps his staff twice': 'tap'},
     'fidgets': ['beard', 'still', 'look_at_you'], 'gutter': ['candle']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# sherlock_deerstalker's clips: writes web/art/sherlock_deerstalker/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/sherlock_deerstalker_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/sherlock_deerstalker/'
K = ROOT + 'art-tools/sherlock_deerstalker_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One long finger taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward.')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Sets a stack down, precise.', lead=1.5)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Lays his cards down, bored.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push his whole stack in, eyes alight.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['fingertips'] = frame('fingertips', 2.8, 0.25, 2.4, 'TELL: puts his fingertips together.', lead=0.5)
C['speck'] = frame('speck', 2.4, 0.22, 2.0, 'IDLE (decoy for the fingertips): examines a speck on the tablecloth.', lead=2)
C['pipe'] = frame('pipe', 2.6, 0.22, 2.2, 'TELL: draws on his pipe.')
C['lens'] = frame('lens', 2.4, 0.22, 2.0, 'IDLE (decoy for the pipe): turns his lens over in his fingers.')
C['pipe_teeth'] = frame('pipe_teeth', 2.4, 0.22, 2.0, 'TELL: taps his pipe stem against his teeth.')
C['your_hands'] = frame('your_hands', 1.8, 0.15, 1.4, 'IDLE (decoy for the pipe stem): glances at your hands.')
C['mantel'] = frame('mantel', 2.2, 0.2, 1.8, 'IDLE: looks at the mantel as if it had lied to him.', lead=-0.5)
C['reading'] = frame('reading', 2.2, 0.2, 1.8, 'IDLE: a sharp, reading look at the player.')
C['bored'] = frame('bored', 2.8, 0.25, 2.4, 'IDLE: leans back, eyes half closed, bored.', lead=-1)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: one finger raised, explaining. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: eyes narrowed, chin on his hand.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a thin, irritated smile.')
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a quick, pleased smile, drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, eyes bright.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: rises, pipe in hand, a curt bow.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.5], ['viewer', 0.24], ['down', 0.12], ['side', 0.14]]
a = {'of': 'sherlock', 'note': "Hand-authored: Holmes's (in the deerstalker) face timing and his clips (poker actions, tells beside their decoys, beats). "
             "He looks at the player more than anyone at the table. rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'puts his fingertips together': 'fingertips',
              'draws on his pipe': 'pipe',
              'taps his pipe stem against his teeth': 'pipe_teeth',
              'examines a speck on the tablecloth': 'speck',
              'glances at your hands': 'your_hands',
              'turns his lens over in his fingers': 'lens',
              'looks at the mantel as if it had lied to him': 'mantel'},
     'fidgets': ['reading', 'bored', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

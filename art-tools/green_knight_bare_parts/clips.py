# green_knight_bare's clips: writes web/art/green_knight_bare/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/green_knight_bare_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/green_knight_bare/'
K = ROOT + 'art-tools/green_knight_bare_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far', 'holly']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'A big finger taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward, unsmiling.')
C['bet'] = frame('bet', 1.7, 0.2, 1.3, 'Shoves a stack forward.', lead=2)
C['fold'] = frame('fold', 1.3, 0.16, 0.9, 'Tosses his cards away.')
C['all_in'] = frame('all_in', 2.0, 0.22, 1.6, 'Both huge hands push his whole stack in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms scoop the pot in.')
C['holly'] = frame('holly', 2.0, 0.15, 1.6, 'TELL: the holly branch at his side rustles.', lead=0.3)
C['moss'] = frame('moss', 2.4, 0.22, 2.0, 'IDLE (decoy for the holly): moss creeps along his sleeve; he watches it.', lead=0.5)
C['laugh'] = frame('laugh', 2.0, 0.15, 1.6, 'TELL: laughs, and the rafters shake.', lead=-1)
C['axe'] = frame('axe', 2.2, 0.22, 1.8, 'TELL: runs a thumb along the head of his axe.', lead=0.5)
C['measure'] = frame('measure', 2.2, 0.22, 1.8, 'IDLE (decoy for the axe): studies the table as if measuring it for a blow.', lead=0.5)
C['door'] = frame('door', 2.0, 0.2, 1.6, 'IDLE: somewhere outside, his horse stamps; he looks toward the door.', lead=0.3)
C['creak'] = frame('creak', 1.8, 0.2, 1.4, 'IDLE: the chair creaks under his weight.', lead=1.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a gauntlet open, booming. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: a challenge accepted.')
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in, eyes fixed.', lead=3)
C['cold_smile'] = frame('cold_smile', 2.0, 0.2, 1.6, 'IDLE (decoy for the laugh): a thin, cold smile.')
C['arrive'] = frame('arrive', 2.8, 0.1, 2.4, 'BEAT: his return: looms over the table, beaten and cold.', lead=-2)
C['lost_pot'] = frame('lost_pot', 2.0, 0.2, 1.6, 'BEAT: lost a pot: a fist on the table, a cold stare.', lead=1)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out for good: rises slowly, a curt nod, turns away.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.7], ['viewer', 0.14], ['down', 0.1], ['side', 0.06]]
face['gaze']['tilt'].pop('narrow', None)
a = {'note': "Hand-authored: the returned Green Knight's face timing and his clips (colder: no grin). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'of': 'green_knight', 'face': face, 'clips': C,
     'cues': {'the holly branch at his side rustles': 'holly', 'laughs, and the rafters shake': 'laugh',
              'runs a thumb along the head of his axe': 'axe', 'moss creeps a little further along his sleeve': 'moss',
              'somewhere outside, his horse stamps': 'door', 'the chair creaks under his weight': 'creak',
              'he studies the table as if measuring it for a blow': 'measure'},
     'fidgets': ['cold_smile', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# Count Dracula's clips: writes web/art/astronaut/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/astronaut_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/astronaut/'
K = ROOT + 'art-tools/astronaut_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two gloved fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A glove cupped low over his cards, eyes down.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A flat glove slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a glove pushed well forward, hopeful.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both gloves push forward, his jaw set.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A glove turns palm up (the game turns the cards).')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A small, resigned push of the glove.')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: gloved fists in the air, a huge grin.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, a glove raised, palm open. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: sitting back, eyebrows up.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a rueful half smile.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: his forehead on his helmet.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, determined.', lead=3)
C['laugh'] = frame('laugh', 2.0, 0.2, 1.6, 'BEAT: a tired laugh, head tipped back.')
C['grin'] = frame('grin', 2.4, 0.22, 2.0, 'TELL: grins, then hides it behind his glove.', lead=0)
C['yawn'] = frame('yawn', 2.4, 0.22, 2.0, 'IDLE (decoy for the grin): yawns, a glove to his mouth.', lead=0)
C['window'] = frame('window', 2.4, 0.22, 2.0, 'TELL: glances out of the window at Earth.', lead=0)
C['photo'] = frame('photo', 2.4, 0.22, 2.0, 'IDLE (decoy for the window): touches the photograph in his sleeve.', lead=0)
C['gauge'] = frame('gauge', 2.4, 0.22, 2.0, 'TELL: checks the oxygen gauge on his wrist.')
C['scuff'] = frame('scuff', 2.4, 0.22, 2.0, 'IDLE (decoy for the gauge): rubs a scuff on his helmet.')
C['token'] = frame('token', 2.4, 0.22, 2.0, 'IDLE: floats a chip an inch off his palm and catches it.', lead=0)
C['turn'] = frame('turn', 2.0, 0.2, 1.6, 'IDLE: turns to look at you, a tired, kind smile.', lead=0)
C['stretch'] = frame('stretch', 2.4, 0.22, 2.0, 'IDLE: rolls his shoulders in the stiff suit.', lead=0)
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.55], ['viewer', 0.15], ['down', 0.2], ['side', 0.1]]
face['gaze']['tilt'] = {k: v for k, v in face['gaze']['tilt'].items() if k in ('ahead', 'down', 'viewer', 'side', 'narrow')}
a = {'note': "Hand-authored: the Astronaut's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'grins, then hides it': 'grin', 'glances out of the window at Earth': 'window',
              'checks the oxygen gauge on his wrist': 'gauge', 'rubs a scuff on his helmet, which sits beside his chips': 'scuff',
              'floats a chip an inch off the table and catches it': 'token', 'touches a photograph tucked in his sleeve': 'photo',
              'yawns': 'yawn'},
     'fidgets': ['turn', 'stretch']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

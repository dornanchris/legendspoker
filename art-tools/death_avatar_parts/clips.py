# Death as a player: writes web/art/death_player/anim.json (face timing, clips,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/death_avatar_parts/clips.py
# He has no tells (the design doc: unreadable): his sheet C is cosmetic loops,
# played as fidgets, which online play needs anyway (rule 3).
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/death_player/'
K = ROOT + 'art-tools/death_avatar_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
dealer = json.load(open(ROOT + 'web/art/death/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A bone hand cupped low over his cards, the hood bowed.')
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One bone finger taps the felt.')
C['call'] = frame('call', 1.5, 0.18, 1.15, "A flat hand slides forward along the felt (the chips are the game's).")
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a hand pushed well forward, unhurried.')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A weary flick of the fingers toward the middle.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push forward along the felt, leaning in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A hand turns palm up (the game turns the cards).')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: arms opened wide, palms up, a host welcoming guests.', lead=-2)
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: the hood bowed, a hand over the brow.')
C['lost_pot'] = frame('lost_pot', 2.0, 0.2, 1.6, 'BEAT: lost a pot: settles the robe on his shoulders, a small shrug.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: elbows on the table, fingers steepled.', lead=3)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, a hand raised, palm open. Play beside a spoken line.')
C['hood'] = frame('hood', 2.4, 0.22, 2.0, 'LOOP: draws the hood a little further forward.', lead=0)
C['brooch'] = frame('brooch', 2.4, 0.22, 2.0, 'LOOP: turns the gold skull brooch between two fingers.', lead=0)
C['ash'] = frame('ash', 2.4, 0.22, 2.0, 'LOOP: brushes a little grey ash from his sleeve.', lead=0)
C['shrug'] = frame('shrug', 2.0, 0.2, 1.6, 'LOOP: settles the robe on his shoulders.', lead=0)
C['flex'] = frame('flex', 2.4, 0.22, 2.0, 'LOOP: flexes his bone fingers one by one.', lead=0)
C['clock'] = frame('clock', 2.4, 0.22, 2.0, 'LOOP: looks up and aside, as at a clock nobody else can see.', lead=0)
face = json.loads(json.dumps(dealer['face']))      # a skull: no blink, eyes ahead, the jaw talks
a = {'note': "Hand-authored: Death as a player (the finale's right-hand chair; later an online avatar). No tells: "
             "his loops are fidgets only. rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'of': 'death', 'face': face, 'clips': C, 'cues': {},
     'fidgets': ['hood', 'brooch', 'ash', 'shrug', 'flex', 'clock']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

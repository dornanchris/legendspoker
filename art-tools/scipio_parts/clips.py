# scipio's clips: writes web/art/scipio/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/scipio_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/scipio/'
K = ROOT + 'art-tools/scipio_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.6, 0.15, 1.2, 'Sets a stack down, in order, well forward.', lead=1.5)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Lays his cards down, without fuss.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Pushes his whole stack in: Zama, then.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['elephant_aside'] = frame('elephant_aside', 2.4, 0.22, 2.0, 'TELL: moves the ivory elephant out of the way.', lead=0.5)
C['tap_trunk'] = frame('tap_trunk', 2.2, 0.22, 1.8, "IDLE (decoy for the elephant moved): taps the ivory elephant's trunk.", lead=0.5)
C['look_up'] = frame('look_up', 2.4, 0.2, 2.0, 'TELL: looks up, as though someone above had advised him.', lead=-0.5)
C['study'] = frame('study', 2.4, 0.22, 2.0, 'IDLE (decoy for the look up): studies each player in turn, like a map.', lead=0.3)
C['elephant_door'] = frame('elephant_door', 2.4, 0.22, 2.0, 'TELL: turns the ivory elephant to face the door.', lead=0.5)
C['ranks'] = frame('ranks', 2.4, 0.22, 2.0, 'IDLE (decoy for the elephant turned): sets his chips out in ranks, with lanes between them.', lead=0.5)
C['cloak'] = frame('cloak', 2.2, 0.2, 1.8, 'IDLE: straightens his cloak, Greek fashion.', lead=-0.3)
C['appraise'] = frame('appraise', 2.2, 0.2, 1.8, 'IDLE: a cool, appraising look at the player.')
C['chin'] = frame('chin', 2.8, 0.25, 2.4, 'IDLE: chin on his fist, thinking.', lead=0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: an open hand, explaining. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: a level, measuring look.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: eyes down, a general taking the lesson.', lead=0.5)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a small smile, drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on his forearms, watching.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: rises with the ivory elephant under his arm, a last look back.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.58], ['viewer', 0.2], ['down', 0.1], ['side', 0.12]]
a = {'note': "Hand-authored: Scipio's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'moves the ivory elephant out of the way': 'elephant_aside',
              'looks up, as though someone above had advised him': 'look_up',
              'turns the ivory elephant to face the door': 'elephant_door',
              'studies each player in turn, like a map': 'study',
              'sets his chips out in ranks, with lanes between them': 'ranks',
              'straightens his cloak, Greek fashion': 'cloak',
              "taps the ivory elephant's trunk": 'tap_trunk'},
     'fidgets': ['appraise', 'chin', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

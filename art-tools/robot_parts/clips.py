# Count Dracula's clips: writes web/art/robot/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/robot_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/robot/'
K = ROOT + 'art-tools/robot_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One metal finger taps the felt, precisely.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A metal hand cupped low over its cards, head tipped down.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A flat hand slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans forward, a hand pushed well forward, exactly.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both metal hands push forward together.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A hand turns palm up (the game turns the cards).')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A neat push of the hand, palm down.')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: both arms straight up, antennae up, lamps bright.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, the grille lit, a hand raised. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: stiffly upright.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: head bowed, lamp eyes dimmed.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: slumped, its lamps gone dark, a wisp of smoke.', lead=0)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning forward on both forearms, lamps bright.', lead=3)
C['laugh'] = frame('laugh', 2.0, 0.2, 1.6, 'BEAT: laughs, the grille glowing in short bars, antennae bobbing.')
C['lamp'] = frame('lamp', 2.4, 0.22, 2.0, 'TELL: its chest lamp flickers.', lead=0)
C['eyes_dim'] = frame('eyes_dim', 2.4, 0.22, 2.0, 'IDLE (decoy for the lamp): its eye-lamps dim and brighten.', lead=0)
C['whir'] = frame('whir', 2.2, 0.22, 1.8, 'TELL: whirs, briefly.', lead=0)
C['recalibrate'] = frame('recalibrate', 2.0, 0.2, 1.6, 'IDLE (decoy for the whir): recalibrates with a click.', lead=0)
C['head_turn'] = frame('head_turn', 2.4, 0.22, 2.0, 'TELL: rotates its head to the pot and back.', lead=0)
C['antennae'] = frame('antennae', 2.2, 0.22, 1.8, 'IDLE (decoy for the head turn): its antennae twitch.', lead=0)
C['steam'] = frame('steam', 2.2, 0.22, 1.8, 'IDLE: vents a thin puff of steam.', lead=0)
C['turn'] = frame('turn', 2.0, 0.2, 1.6, 'IDLE: turns to look at you, both lamp eyes on you.', lead=0)
C['polish'] = frame('polish', 2.4, 0.22, 2.0, 'IDLE: polishes a scratch on its chest.')
face = json.loads(json.dumps(kidd['face']))
face['blink'] = {'every': [4.5, 9.0], 'double': 0, 'frames': [['half', 0.06], ['closed', 0.08], ['half', 0.06]]}   # shutters, now and then
face['gaze']['idle'] = [['ahead', 0.65], ['viewer', 0.15], ['down', 0.2]]
face['gaze']['tilt'] = {k: v for k, v in face['gaze']['tilt'].items() if k in ('ahead', 'down', 'viewer', 'narrow')}
a = {'note': "Hand-authored: the Robot's face timing and its clips (poker actions, tells beside their decoys, beats). "
             "It blinks its shutters now and then; it talks by its own grille lighting up (glow.py). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'its chest lamp flickers': 'lamp', 'whirs, briefly': 'whir', 'rotates its head to the pot and back': 'head_turn',
              'recalibrates with a click': 'recalibrate', 'its antennae twitch': 'antennae',
              'vents a thin puff of steam': 'steam', 'its eye-lamps dim and brighten': 'eyes_dim'},
     'fidgets': ['turn', 'polish']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

"""Lincoln's IK prototype: split his existing check arm piece into three images.

    python3 art-tools/lincoln_parts/ik_split.py

No new drawing: web/art/lincoln/arm_near_check.png (the forearm, cuff and
pointing hand of pose A3, already cut by pose_rig.py) and upper_near.png (the
sleeve over the elbow) are cut along the elbow and the cuff into an upper arm,
a forearm and a hand, each cropped and written with where it sits in the rig
(rig pixels). web/art/lincoln/ik.json says where the shoulder, elbow, wrist
and fingertip are, and which slots the chain stands in for while it moves.
Half-size copies go to half/, as web_half.py makes for every other image.
"""
import json, os
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ART = os.path.join(ROOT, 'web', 'art', 'lincoln')
rig = json.load(open(os.path.join(ART, 'rig.json')))
part = {p['name']: p for p in rig['parts']}

# joints, rig pixels (found on a grid over the check piece; the elbow is the rig's own arm_near pivot)
SHOULDER = [375.0, 690.0]
ELBOW = next(b['pivot'] for b in rig['bones'] if b['name'] == 'arm_near')
WRIST = [447.0, 857.0]
TIP = [556.0, 906.0]          # the checking finger's tip, on the felt


def placed(name):
    """The part's image as an RGBA array, and its top-left corner in rig pixels (rest pose, scale 1)."""
    p = part[name]
    assert p['scale'] == 1 and not p['flip'] and p['rot'] == 0
    im = np.array(Image.open(os.path.join(ART, p['img'])).convert('RGBA'))
    h, w = im.shape[:2]
    return im, (p['cx'] - w / 2, p['cy'] - h / 2)


check, (ox, oy) = placed('arm_near.check')
upper_patch, (ux, uy) = placed('upper_near')
assert (ox, oy) == (ux, uy)
h, w = check.shape[:2]
ys, xs = np.mgrid[0:h, 0:w]
X, Y = xs + ox, ys + oy                                    # rig pixels of every image pixel

# the hand: right of the cuff's edge (a line leaning a little, as the cuff does);
# 5 px of it run under the cuff, which the forearm draws over
cuff = 443 + (Y - 820) * 0.15
hand = X > cuff - 5
# the upper arm: the sleeve standing above the bend, with the patch drawn over the elbow
upper = (Y < 836) & (X < 405)
fore = (X <= cuff + 1) & ~(Y < 826) | ((Y < 836) & (Y >= 826) & (X < 405))   # 10 px of overlap in the bend


def write(name, mask, src=check, z=0.0, on_table=False):
    a = src.copy()
    a[..., 3] = np.where(mask, a[..., 3], 0)
    yy, xx = np.nonzero(a[..., 3] > 0)
    t, b, l, r = yy.min(), yy.max() + 1, xx.min(), xx.max() + 1
    crop = Image.fromarray(a[t:b, l:r])
    crop.save(os.path.join(ART, f'ik_{name}.png'), optimize=True)
    crop.resize((max(1, crop.width // 2), max(1, crop.height // 2)), Image.LANCZOS).save(
        os.path.join(ART, 'half', f'ik_{name}.png'), optimize=True)
    return {'img': f'ik_{name}.png', 'x': round(ox + l, 2), 'y': round(oy + t, 2), 'z': z, 'onTable': on_table}


up = write('upper_near', upper | (upper_patch[..., 3] > 0), src=np.where(upper_patch[..., 3:] > 0, upper_patch, check), z=24, on_table=False)
fo = write('fore_near', fore & ~hand | ((X <= cuff + 1) & (X > cuff - 5)), z=23, on_table=True)
# the drawing's coat behind the hand came with it: dark areas thicker than an
# outline go, or they show as a dark band once the hand reaches over the rail
dark = check[..., :3].max(-1) < 80
ha = write('hand_near_point', hand & ~ndimage.binary_dilation(ndimage.binary_opening(dark, iterations=4), iterations=1), z=22.9, on_table=True)

ik = {
    'note': 'GENERATED by art-tools/lincoln_parts/ik_split.py: the IK prototype (two-bone arm). Rig pixels. '
            'While the chain shows a hand state it stands in for the slots in "hides".',
    'chains': [{
        'chain': 'arm_near', 'bone': 'torso',
        'shoulder': SHOULDER, 'elbow': ELBOW, 'wrist': WRIST, 'tip': TIP,
        'hides': ['arm_near', 'upper_near'],
        'parts': {'upper': up, 'fore': fo, 'hands': {'point': ha}},
    }],
}
json.dump(ik, open(os.path.join(ART, 'ik.json'), 'w'), indent=1)
print('wrote ik.json and', up['img'], fo['img'], ha['img'])

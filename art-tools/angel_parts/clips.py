# Pravuil, the Recording Angel: writes web/art/pravuil/anim.json (face timing,
# clips) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/angel_parts/clips.py
# He deals the finale while Death plays, so his clips carry the dealer's names
# (deal_left, flop, push_right ...): the table asks the dealer for those, whoever
# deals. Every pose is a whole-figure frame with its own drawn head; the drawing
# changes inside a small dip of the body, as Death's do. No tells: he is the house.
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/pravuil/'
K = ROOT + 'art-tools/angel_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far', 'head']
DIP = 1.2

def seq(steps, end, dur, note, dip=DIP):
    """steps: [(time, frame)], each drawing held until the next; back to rest at `end`."""
    for _, f in steps: assert f in rig['frames'], f
    sw = {s: [[t, '-'] for t, _ in steps] + [[end, N]] for s in BODY}
    sw['frame'] = [[t, f] for t, f in steps] + [[end, N]]
    y = [[0, 0]]
    for t in [t for t, _ in steps] + [end]:
        y += [[max(t - 0.08, y[-1][0]), 0], [t, dip, 'in'], [t + 0.12, 0, 'out']]
    y.append([dur, 0])
    return {'duration': dur, 'note': note, 'tracks': {'torso': {'y': y}}, 'swaps': sw}

C = {}
C['deal_left'] = seq([(0.05, 'thumb'), (0.3, 'pitch_left')], 0.75, 1.0,
                     'Deals a card to a seat on the left of the picture: thumbs it off, pitches it (the game flies the card).')
C['deal_right'] = seq([(0.05, 'thumb'), (0.3, 'pitch_right')], 0.75, 1.0,
                      'Deals a card to a seat on the right of the picture.')
C['deal_you'] = seq([(0.05, 'thumb'), (0.3, 'slide')], 0.75, 1.0, 'Deals a card to you, sliding it forward.')
C['burn'] = seq([(0.15, 'burn')], 0.75, 1.0, 'Burns a card face down beside the deck.')
C['flop'] = seq([(0.15, 'flop')], 1.05, 1.3, 'Lays the flop in a row in the middle.')
C['turn'] = seq([(0.15, 'turn')], 0.95, 1.2, 'Turns a card on the board (turn, river, a shown hand).')
C['shuffle'] = seq([(0.12, 'riffle'), (0.55, 'square'), (0.85, 'riffle'), (1.3, 'square')], 1.9, 2.2,
                   'Riffles the deck twice and squares it.')
C['cut'] = seq([(0.15, 'cut')], 1.05, 1.3, 'Cuts the deck.')
C['rake'] = seq([(0.15, 'rake')], 1.25, 1.5, 'Rakes the bets into the middle at the end of a street.')
C['push_left'] = seq([(0.15, 'push_left')], 1.25, 1.5, 'Pushes the pot to a seat on the left of the picture.')
C['push_you'] = seq([(0.15, 'push_you')], 1.35, 1.6, 'Pushes the pot to you.')
C['push_right'] = seq([(0.15, 'push_right')], 1.25, 1.5, 'Pushes the pot to a seat on the right of the picture.')
C['steeple'] = seq([(0.3, 'steeple')], 2.6, 3.0, 'Heads-up and the last card: leans in, hands clasped, watching.', dip=2)
# his two beats, asked for as the dealer's idle ('weary' / 'look_up')
C['weary'] = seq([(0.3, 'wings')], 2.4, 2.8, 'BEAT: the folded wings settle, a small shrug.', dip=0)
C['look_up'] = seq([(0.25, 'quill')], 2.2, 2.6, 'BEAT: takes the quill from behind his ear, as if to write something down.', dip=0)
C['quill'] = C['look_up']; C['wings'] = C['weary']

face = {
    'blink': {'every': [3.2, 7.5], 'double': 0.1, 'frames': [['half', 0.05], ['closed', 0.08], ['half', 0.05]]},
    'gaze': {'idle': [['ahead', 0.62], ['left', 0.14], ['right', 0.14], ['down', 0.1]], 'hold': [1.8, 3.6],
             'tilt': {'ahead': [0, 0, 0], 'left': [-0.6, -1.5, 0], 'right': [0.6, 1.5, 0], 'down': [1.2, 0, 2]}},
    'sway': {'rot': 0.55, 'x': 1.1, 'y': 0.7, 'periods': [7.9, 9.7, 6.3], 'follow': 3, 'body': 0.225},
    'breath': {'period': 5.6, 'sy': 0.0065},
    'speech': {'vowel': 0.1, 'consonant': 0.065, 'space': 0.055, 'pause': 0.35,
               'map': {c: 'open' for c in 'aeiouyhkgrw'} | {c: 'closed' for c in 'mbpfvsz'}
                      | {c: 'open' for c in 'lntdcjxq'} | {'th': 'open'}},
}
a = {'note': "Hand-authored: Pravuil, the Recording Angel, the finale's dealer while Death plays (front-on, "
             "never mirrored). Every pose is a whole-figure frame with its own drawn head, inside a small dip of "
             "the body. No tells. rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'dealer': True, 'face': face, 'clips': C}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

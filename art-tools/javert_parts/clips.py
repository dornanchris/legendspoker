# javert's clips: writes web/art/javert/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/javert_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/javert/'
K = ROOT + 'art-tools/javert_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One finger taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward.')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Sets a stack down, exact.', lead=1.5)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Lays his cards down, squared together.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push his whole stack in, rigid.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['button'] = frame('button', 2.4, 0.22, 2.0, 'TELL: buttons his coat to the collar.', lead=-0.3)
C['stock'] = frame('stock', 2.2, 0.2, 1.8, 'IDLE (decoy for the buttoning): straightens his stock.', lead=-0.3)
C['stare'] = frame('stare', 2.8, 0.25, 2.4, 'TELL: stares at you without blinking.')
C['door'] = frame('door', 2.2, 0.2, 1.8, 'IDLE (decoy for the stare): glances at the door like a man expecting an escape.', lead=-0.3)
C['shake'] = frame('shake', 2.4, 0.22, 2.0, 'TELL: his hand shakes, very slightly.')
C['cane'] = frame('cane', 1.6, 0.15, 1.2, 'IDLE (decoy for the shaking hand): taps his cane on the floor once.', lead=1)
C['notebook'] = frame('notebook', 2.6, 0.22, 2.2, 'IDLE: consults a small black notebook.', lead=-0.3)
C['upright'] = frame('upright', 2.6, 0.22, 2.2, 'IDLE: sits bolt upright, arms rigid on the table.', lead=-1)
C['bicorne'] = frame('bicorne', 2.0, 0.2, 1.6, 'IDLE: settles his bicorne lower on his brow.', lead=-0.3)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a finger pointed, an accusation. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: eyes narrowed under the bicorne.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a stiff, grim nod.')
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: no smile, drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, eyes hard.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: rises, buttons his coat to the collar, a stiff bow.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.66], ['viewer', 0.16], ['down', 0.08], ['side', 0.1]]
face['blink']['every'] = [3.5, 7.5]
a = {'note': "Hand-authored: Javert's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "He blinks less than anyone at the table. rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'buttons his coat to the collar': 'button',
              'stares at you without blinking': 'stare',
              'his hand shakes, very slightly': 'shake',
              'straightens his stock': 'stock',
              'consults a small black notebook': 'notebook',
              'glances at the door like a man expecting an escape': 'door',
              'taps his cane on the floor once': 'cane'},
     'fidgets': ['upright', 'bicorne', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

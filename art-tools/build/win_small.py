"""The small win, for every puppet: a satisfied nod and a smile, from the head
and mouth each puppet already has (no new drawing).

    python3 art-tools/build/win_small.py

Writes `win_small` into every web/art/<id>/anim.json (not Death's), and
`win`: which clip the table plays for a small pot and for a big one (and
`lose`: `lost_pot`, or `lose_big` for a big pot once that is drawn).
  * small: `win_small`.
  * big: `win_big` once a puppet has one (the hands-raised drawing); until
    then its old `won_pot` beat, unless that beat is the pot drawn in by hand
    (the owner: raking in the chips is the chips' job, and lame), when the
    small win serves for both.
The mouth is the first smile-like shape the puppet has, never one its own
tells use (a smile after a pot must not look like a tell); stern characters
only nod.
"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SMILES = ['smile', 'pleased', 'beam', 'grin', 'half_smile', 'wry', 'proud', 'enormous', 'pant']
NOD_ONLY = {'javert', 'leonidas', 'green_knight',          # no smile for them
            'caesar', 'socrates'}                         # their smile is a tell, drawn as a whole frame
CHIPS = re.compile(r'chip|gather|drawing|dragging|sweep', re.I)


def mouths(art):
    rig = json.load(open(os.path.join(art, 'rig.json')))
    return {p['name'].split('.', 1)[1] for p in rig['parts'] if p.get('slot') == 'mouth' and '.' in p['name']}


def tell_mouths(anim, cid):
    """Mouth shapes the character's tell clips swap to."""
    f = os.path.join(ROOT, 'data', 'characters', f'{cid}.json')
    if not os.path.exists(f):
        return set()
    texts = [t['text'] for t in json.load(open(f)).get('tells', [])]
    out = set()
    for text in texts:
        clip = anim['clips'].get(anim.get('cues', {}).get(text, ''), {})
        out |= {s for _, s in clip.get('swaps', {}).get('mouth', []) if s}
    return out


for path in sorted(glob.glob(os.path.join(ROOT, 'web', 'art', '*', 'anim.json'))):
    art = os.path.dirname(path)
    pid = os.path.basename(art)
    if pid in ('death', 'rooms'):
        continue
    raw = open(path).read()
    anim = json.loads(raw)
    cid = anim.get('of', pid)
    banned = tell_mouths(anim, cid)
    have = mouths(art)
    mouth = None if pid in NOD_ONLY or cid in NOD_ONLY else next((m for m in SMILES if m in have and m not in banned), None)
    clip = {
        'duration': 1.6,
        'note': 'BEAT (GENERATED by art-tools/build/win_small.py): won a small pot: two satisfied nods'
                + (f', the {mouth} mouth.' if mouth else ', no smile.'),
        'tracks': {'head': {
            'rot': [[0, 0], [0.22, 3, 'inOut'], [0.45, 0.2, 'inOut'], [0.68, 2.2, 'inOut'], [0.95, 0, 'inOut']],
            'y': [[0, 0], [0.22, 1.2, 'inOut'], [0.45, 0, 'inOut'], [0.68, 0.8, 'inOut'], [0.95, 0, 'inOut']],
        }},
    }
    if mouth:
        clip['swaps'] = {'mouth': [[0.12, mouth], [1.45, None]]}
    anim['clips']['win_small'] = clip
    won = anim['clips'].get('won_pot')
    big = 'win_big' if 'win_big' in anim['clips'] else 'won_pot' if won and not CHIPS.search(won.get('note', '')) else 'win_small'
    anim['win'] = {'small': 'win_small', 'big': big}
    # and the loser's side: the old beat, or the crushing loss once it is drawn
    lost = 'lost_pot' if 'lost_pot' in anim['clips'] else None
    if lost:
        anim['lose'] = {'small': lost, 'big': 'lose_big' if 'lose_big' in anim['clips'] else lost}
    end = '\n' if raw.endswith('\n') else ''
    open(path, 'w').write(json.dumps(anim, indent=1, ensure_ascii=False) + end)
    print(f'{pid:22} mouth {mouth or "-":12} big {big}' + (f'   (tells use {sorted(banned)})' if banned else ''))

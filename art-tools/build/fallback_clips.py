"""Clips the table asks for, made from the rest pose where a puppet has no
drawing for them:

    python3 art-tools/build/fallback_clips.py

  * heads_up (down to two players): leans in on the table, a little closer,
    eyes on the player. Lincoln's and Odysseus's sheets had no lean.
A puppet that has the clip keeps its own. Going out needs nothing: a figure
with no knocked_out clip says its line and fades from the chair (stage.ts).
"""
import glob, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

for path in sorted(glob.glob(os.path.join(ROOT, 'web', 'art', '*', 'anim.json'))):
    pid = os.path.basename(os.path.dirname(path))
    if pid in ('death', 'pravuil'):
        continue
    raw = open(path).read()
    anim = json.loads(raw)
    if 'heads_up' in anim['clips']:
        continue
    rig = json.load(open(os.path.join(os.path.dirname(path), 'rig.json')))
    eyes = {p['name'].split('.', 1)[1] for p in rig['parts'] if p.get('slot') == 'eyes' and '.' in p['name']}
    clip = {
        'duration': 2.6,
        'note': 'BEAT (GENERATED by art-tools/build/fallback_clips.py): down to two: leans in on the table, closer, eyes on the player.',
        'tracks': {
            'torso': {'y': [[0, 0], [0.5, 6, 'inOut'], [2.0, 6], [2.5, 0, 'inOut']],
                      'sx': [[0, 0], [0.5, 0.035, 'inOut'], [2.0, 0.035], [2.5, 0, 'inOut']],
                      'sy': [[0, 0], [0.5, 0.035, 'inOut'], [2.0, 0.035], [2.5, 0, 'inOut']]},
            'head': {'rot': [[0, 0], [0.5, -1.2, 'inOut'], [2.0, -1.2], [2.5, 0, 'inOut']]},
        },
    }
    if 'viewer' in eyes:
        clip['swaps'] = {'eyes': [[0.4, 'viewer'], [2.2, None]]}
    anim['clips']['heads_up'] = clip
    open(path, 'w').write(json.dumps(anim, indent=1, ensure_ascii=False) + ('\n' if raw.endswith('\n') else ''))
    print(f'{pid:22} heads_up from rest' + (' (eyes on the player)' if 'viewer' in eyes else ''))

"""Death as a player (the finale: he is the opponent, heads up). His kit was
drawn for dealing, so the clips the table asks of a player that he has no
drawing for are his dealer's clips under their names:

    python3 art-tools/build/death_player.py

  * call: his bet (a hand pushed forward over the felt)
  * heads_up: his steepled fingers (which the table also plays at any heads up)
A clip he already has is kept.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
path = os.path.join(ROOT, 'web', 'art', 'death', 'anim.json')
raw = open(path).read()
anim = json.loads(raw)
for name, src in (('call', 'bet'), ('heads_up', 'steeple')):
    if name in anim['clips'] or src not in anim['clips']:
        continue
    clip = json.loads(json.dumps(anim['clips'][src]))
    clip['note'] = f'(GENERATED by art-tools/build/death_player.py) the finale, Death as a player: his `{src}` clip. ' + clip.get('note', '')
    anim['clips'][name] = clip
    print('death', name, 'from', src)
open(path, 'w').write(json.dumps(anim, indent=1, ensure_ascii=False) + ('\n' if raw.endswith('\n') else ''))

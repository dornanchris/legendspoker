# jfk's clips: writes web/art/jfk/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/jfk_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/jfk/'
K = ROOT + 'art-tools/jfk_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A hand cupped low over his cards, thumb lifting, eyes down.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A flat hand slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a hand pushed well forward.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push forward together.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A hand turns palm up (the game turns the cards).')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: both fists raised high.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, one hand in the air. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, eyes level.', lead=3)
C['laugh'] = frame('laugh', 2.0, 0.2, 1.6, 'BEAT: laughs, head back a little.')
C['arrive'] = frame('arrive', 2.2, 0.0, 1.8, 'BEAT: played as he sits down: looking round the table.', lead=-2)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'An easy flick of the hand toward the middle.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a rueful half-smile, a small shrug.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: a hand over his eyes, a rueful shake of the head.')
C['rock_back'] = frame('rock_back', 2.4, 0.22, 2.0, 'TELL: rocks back in his chair, easy.', lead=-1.5)
C['hair'] = frame('hair', 2.4, 0.22, 2.0, 'IDLE (decoy for rocking back): runs a hand through his hair.', lead=0)
C['tie'] = frame('tie', 2.2, 0.22, 1.8, 'TELL: straightens his tie.', lead=0)
C['chop'] = frame('chop', 2.2, 0.22, 1.8, 'IDLE (decoy for the tie): chops the air with one hand, mid-thought.', lead=0)
C['back'] = frame('back', 2.4, 0.22, 2.0, 'TELL: presses a hand to the small of his back.', lead=0)
C['tap_shell'] = frame('tap_shell', 2.2, 0.22, 1.8, 'IDLE (decoy for his back): taps the coconut shell on the felt.')
C['portraits'] = frame('portraits', 2.2, 0.2, 1.8, 'IDLE: glances up at the portraits on the wall.', lead=0)
C['grin'] = frame('grin', 2.0, 0.2, 1.6, 'IDLE: a broad grin at the table.', lead=0)

C['look_at_you'] = {'duration': 2.0, 'note': 'BEAT: looks straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -0.8, 'in'], [0.3, 0, 'out'], [1.6, 0], [1.7, -0.8, 'in'], [1.9, 0, 'out']]}},
                    'swaps': {'eyes': [[0.15, 'viewer'], [1.7, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.15], ['down', 0.25]]
face['gaze']['tilt'] = {k: v for k, v in face['gaze']['tilt'].items() if k in ('ahead', 'down', 'viewer', 'narrow')}
a = {'note': "Hand-authored: Kennedy's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'rocks back in his chair, easy': 'rock_back', 'straightens his tie': 'tie', 'presses a hand to the small of his back': 'back', 'runs a hand through his hair': 'hair', 'taps the coconut shell on the felt': 'tap_shell', 'chops the air with one hand, mid-thought': 'chop', 'glances up at the portraits on the wall': 'portraits'},
     'fidgets': ['grin', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

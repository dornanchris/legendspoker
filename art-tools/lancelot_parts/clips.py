# lancelot's clips: writes web/art/lancelot/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/lancelot_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/lancelot/'
K = ROOT + 'art-tools/lancelot_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.7, 0.2, 1.3, 'Pushes a tall stack forward with a flourish.', lead=2)
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Flicks his cards away, disdainful.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Drives his whole stack forward, like a charge.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms sweep the pot in.')
C['polish'] = frame('polish', 2.4, 0.22, 2.0, 'TELL: polishes his gauntlet with a cloth.', lead=0.5)
C['reflection'] = frame('reflection', 2.2, 0.22, 1.8, 'IDLE (decoy for the polish): admires his reflection in his breastplate.', lead=1)
C['hair'] = frame('hair', 1.8, 0.15, 1.4, 'TELL: tosses his hair back.', lead=-0.5)
C['sigh'] = frame('sigh', 2.2, 0.22, 1.8, 'IDLE (decoy for the hair toss): sighs, for no clear reason.', lead=-0.5)
C['door'] = frame('door', 2.0, 0.2, 1.6, 'TELL: glances toward the door.', lead=0.3)
C['chair'] = frame('chair', 2.4, 0.22, 2.0, 'IDLE (decoy for the door): looks toward an empty chair.', lead=0.3)
C['sword'] = frame('sword', 2.0, 0.22, 1.6, 'IDLE: adjusts his sword belt.', lead=1)
C['bored'] = frame('bored', 2.8, 0.25, 2.4, 'IDLE: leans back, arms folded, faintly bored.', lead=-1)
C['proud'] = frame('proud', 2.0, 0.2, 1.6, 'IDLE: a small proud smile, chin raised.', lead=-0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: one gauntleted hand raised, declaiming. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: a challenge accepted.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: wounded pride, looking away.', lead=-1)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a dazzling smile, sweeping chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in, eyes blazing.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: a stiff, proud bow, turning away.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.18], ['down', 0.12], ['side', 0.1]]
a = {'note': "Hand-authored: Lancelot's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'polishes his gauntlet': 'polish', 'tosses his hair': 'hair', 'glances toward the door': 'door',
              'admires his reflection in his breastplate': 'reflection', 'adjusts his sword belt': 'sword',
              'sighs, for no clear reason': 'sigh', 'looks toward an empty chair': 'chair'},
     'fidgets': ['bored', 'proud', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# arthur's clips: writes web/art/arthur/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/arthur_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/arthur/'
K = ROOT + 'art-tools/arthur_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.6, 0.15, 1.2, 'Sets a stack down firmly, at once.', lead=1.5)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Lays his cards down, gracefully.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Pushes his whole stack in, resolute.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['hilt'] = frame('hilt', 2.4, 0.22, 2.0, "TELL: rests his hand on Excalibur's hilt.", lead=0.5)
C['dent'] = frame('dent', 2.2, 0.22, 1.8, 'IDLE (decoy for the hilt): rubs the dent in his crown.', lead=0.5)
C['crown'] = frame('crown', 2.4, 0.2, 2.0, 'TELL: his crown slips a fraction; he does not fix it.', lead=0.3)
C['wind'] = frame('wind', 2.4, 0.22, 2.0, 'IDLE (decoy for the crown): listens to the wind at the window.', lead=-0.5)
C['knights'] = frame('knights', 2.4, 0.22, 2.0, 'TELL: looks round the table at each of his knights.', lead=0.3)
C['servant'] = frame('servant', 1.8, 0.2, 1.4, 'IDLE (decoy for the look round): nods to a servant who is not there.', lead=0.5)
C['fond'] = frame('fond', 2.2, 0.2, 1.8, 'IDLE: a tired, fond smile at the table.')
C['cup'] = frame('cup', 2.4, 0.22, 2.0, 'IDLE: raises his cup to the table.', lead=-0.5)
C['listen'] = frame('listen', 2.8, 0.25, 2.4, 'IDLE: hands folded, a king listening.', lead=0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: an open hand, gracious. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: a steady look, considering.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a gracious nod, a small sad smile.', lead=0.5)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a warm smile, drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in, steady and calm.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: takes up Excalibur and bows his head to the table.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.18], ['down', 0.12], ['side', 0.1]]
a = {'note': "Hand-authored: Arthur's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {"rests his hand on Excalibur's hilt": 'hilt', 'looks round the table at each of his knights': 'knights',
              'his crown slips a fraction; he does not fix it': 'crown', 'raises his cup to the table': 'cup',
              'rubs the dent in his crown': 'dent', 'listens to the wind at the window': 'wind',
              'nods to a servant who is not there': 'servant'},
     'fidgets': ['fond', 'listen', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# The Headless Horseman's clips: writes web/art/headless_horseman/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/headless_horseman_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/headless_horseman/'
K = ROOT + 'art-tools/headless_horseman_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'A gauntleted finger taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A gauntlet cupped low over his cards, the pumpkin tipped down to them.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A flat gauntlet slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a gauntlet pushed well forward.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both gauntlets push forward together, the pumpkin leaning in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A gauntlet turns palm up (the game turns the cards).')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'A curt flick of the gauntlet toward the middle.')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: both gauntlets raised high, clenched.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking, a gauntlet raised, palm open. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: leaning back, gauntlets flat.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: shoulders slumped, the pumpkin tipped forward, its light dimmed.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: a gauntlet slammed flat, the pumpkin bowed low.', lead=0)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, the pumpkin lowered toward you.', lead=3)
C['nod'] = frame('nod', 2.0, 0.25, 1.6, 'BEAT: a slow, grave nod to the table.', lead=0)
C['brighter'] = frame('brighter', 2.4, 0.22, 2.0, 'TELL: the candle in his pumpkin burns brighter.', lead=0)
C['settle'] = frame('settle', 2.4, 0.22, 2.0, 'IDLE (decoy for the candle): settles the pumpkin on his collar.', lead=0)
C['gutter'] = frame('gutter', 2.4, 0.22, 2.0, 'TELL: the flame in his pumpkin gutters, a curl of smoke.', lead=0)
C['leaves'] = frame('leaves', 2.4, 0.22, 2.0, 'IDLE (decoy for the flame): a smell of cold leaves drifts from him.', lead=0)
C['drum'] = frame('drum', 2.2, 0.22, 1.8, 'TELL: drums a gauntlet on the table.')
C['sword'] = frame('sword', 2.2, 0.22, 1.8, 'IDLE (decoy for the drumming): his sword rattles in its scabbard.')
C['turn'] = frame('turn', 2.4, 0.2, 2.0, 'IDLE: turns his whole body to look at you.', lead=0)
C['cloak'] = frame('cloak', 2.2, 0.2, 1.8, 'IDLE: draws his cloak about his shoulders.')
C['still'] = frame('still', 2.6, 0.3, 2.2, 'IDLE: sits very still, the pumpkin tilted toward the pot, listening.', lead=0)
face = json.loads(json.dumps(kidd['face']))
face['blink'] = {'every': [3600, 3600], 'double': 0, 'frames': []}     # a pumpkin does not blink
face['gaze']['idle'] = [['ahead', 1]]                                  # nor glance: he turns (`turn`)
face['gaze']['tilt'] = {'ahead': [0, 0, 0]}
a = {'note': "Hand-authored: the Headless Horseman's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "He has no face: speech brightens the candlelight in his carving (glow.py), and he never blinks or glances. "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'the candle in his pumpkin burns brighter': 'brighter', 'the flame in his pumpkin gutters': 'gutter',
              'drums a gauntlet on the table': 'drum', 'settles the pumpkin on his collar': 'settle',
              'his sword rattles in its scabbard': 'sword', 'turns his whole body to look at you': 'turn',
              'a smell of cold leaves drifts from him': 'leaves'},
     'fidgets': ['cloak', 'still']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# cyclops's clips: writes web/art/cyclops/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/cyclops_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/cyclops/'
K = ROOT + 'art-tools/cyclops_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
rose = json.load(open(ROOT + 'web/art/roosevelt/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One huge knuckle raps the felt.')
C['peek'] = frame('peek', 1.7, 0.2, 1.3, 'Bends down to his cards, the great eye close to them (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.6, 0.2, 1.2, 'Plants a tall stack well forward.')
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Sweeps his cards away.')
C['all_in'] = frame('all_in', 2.0, 0.22, 1.6, 'Shoves his whole stack in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Draws the pot in with both hands.')
C['narrow'] = frame('narrow', 2.0, 0.22, 1.6, 'TELL: his eye narrows.', lead=1)
C['blink'] = frame('blink', 1.8, 0.25, 1.3, 'IDLE (decoy for the narrowed eye): blinks, very slowly.', lead=0.5)
C['sniff'] = frame('sniff', 2.0, 0.22, 1.6, 'TELL: sniffs at the air.', lead=-1)
C['listen'] = frame('listen', 2.2, 0.25, 1.8, 'IDLE (decoy for the sniff): tilts his head, listening.', lead=-1)
C['thump'] = frame('thump', 1.4, 0.12, 0.9, 'TELL: thumps the table with his fist.', lead=4)
C['shift'] = frame('shift', 2.0, 0.22, 1.6, 'IDLE (decoy for the thump): shifts his weight; the table groans.', lead=3)
C['count'] = frame('count', 2.6, 0.25, 2.2, 'IDLE: counts his sheep on his fingers.')
C['beard'] = frame('beard', 2.2, 0.22, 1.8, 'IDLE: scratches his beard with a thumbnail the size of a spoon.')
C['club'] = frame('club', 2.0, 0.22, 1.6, 'IDLE: rests his hand on the head of his club.')
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a huge finger pointed across the table. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: the eye wide, suspicious.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.25, 1.8, 'BEAT: lost a pot: a growl, teeth bared.')
C['won_pot'] = frame('won_pot', 2.0, 0.22, 1.6, 'BEAT: won a pot: a huge gap-toothed grin.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both fists, the eye fixed.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: picks up his club to go.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(rose['face']))
face['gaze']['tilt']['wide'] = [0, 0, -0.5]
a = {'note': "Hand-authored: the Cyclops's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'his eye narrows': 'narrow', 'sniffs at the air': 'sniff', 'thumps the table': 'thump',
              'counts his sheep on his fingers': 'count', 'blinks, very slowly': 'blink',
              'scratches his beard with a thumbnail the size of a spoon': 'beard', 'the table groans as he shifts': 'shift'},
     'fidgets': ['listen', 'club', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

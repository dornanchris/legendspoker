# davy_jones's clips: writes web/art/davy_jones/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/davy_jones_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/davy_jones/'
K = ROOT + 'art-tools/davy_jones_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One finger taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.8, 0.25, 1.4, 'Sets a stack down, slow and calm.', lead=1)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Slides his cards away without a flicker.')
C['all_in'] = frame('all_in', 2.2, 0.3, 1.8, 'Pushes his whole stack in with both hands, unhurried.', lead=2)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['drip'] = frame('drip', 2.4, 0.25, 2.0, 'TELL: sea water drips hard from his sleeve, pooling on the felt.', lead=0.5)
C['wring'] = frame('wring', 2.4, 0.25, 2.0, 'IDLE (decoy for the drip): wrings out his beard.', lead=0.5)
C['drum'] = frame('drum', 2.2, 0.22, 1.8, 'TELL: drums on the table like rain on a deck.', lead=0.5)
C['hum'] = frame('hum', 2.6, 0.25, 2.2, 'IDLE (decoy for the drumming): hums a shanty, eyes half closed, fingers still.', lead=0.3)
C['shadow'] = frame('shadow', 2.4, 0.25, 2.0, 'TELL: the lamp nearest him flickers: his face sinks into shadow, only the pale eyes lit.', lead=0.3)
C['light'] = frame('light', 2.2, 0.22, 1.8, 'IDLE (decoy for the shadow): lifts his face into the lamplight.', lead=-0.5)
C['crab'] = frame('crab', 2.8, 0.3, 2.4, 'IDLE: a crab climbs out of his pocket; he watches it.', lead=0.5)
C['haze'] = frame('haze', 2.8, 0.3, 2.4, 'IDLE: the haze of low tide curls up from his coat.', lead=0.3)
C['hat_water'] = frame('hat_water', 2.2, 0.22, 1.8, 'IDLE: tips water off his hat brim.', lead=-0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a quiet word, one hand turned up. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.4, 0.25, 2.0, 'BEAT: facing a big bet: the pale eyes fixed, unblinking.', lead=0.5)
C['lost_pot'] = frame('lost_pot', 2.2, 0.22, 1.8, 'BEAT: lost a pot: no flicker at all, a slow nod.', lead=1)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: the faintest smile, drawing the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on his forearms, eyes fixed.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: rises, water streaming from him, and turns away.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.7], ['viewer', 0.14], ['down', 0.1], ['side', 0.06]]
face['blink']['every'] = [8, 16]  # pale, unblinking eyes
face['gaze']['tilt'].pop('narrow', None)
a = {'note': "Hand-authored: Davy Jones's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'sea water drips from his sleeve': 'drip', 'drums on the table like rain on a deck': 'drum',
              'the lamp nearest him flickers': 'shadow', 'a crab climbs out of his pocket': 'crab',
              'hums a shanty under his breath': 'hum', 'wrings out his beard': 'wring',
              'the smell of low tide drifts across the table': 'haze'},
     'fidgets': ['light', 'hat_water', 'look_at_you'], 'gutter': ['shadow']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

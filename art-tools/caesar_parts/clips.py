# caesar's clips: writes web/art/caesar/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/caesar_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/caesar/'
K = ROOT + 'art-tools/caesar_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingers tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward.')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Sets a stack down, decisive.', lead=1.5)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'Lays his cards down, dismissive.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push his whole stack in: the die is cast.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms draw the pot in.')
C['wreath'] = frame('wreath', 2.2, 0.2, 1.8, 'TELL: adjusts his laurel wreath, setting it lower.', lead=-0.3)
C['temple'] = frame('temple', 2.4, 0.22, 2.0, 'IDLE (decoy for the wreath): rubs his temple, eyes half closed.', lead=0.3)
C['drum'] = frame('drum', 2.4, 0.22, 2.0, "TELL: drums his fingers on the table's edge.", lead=0.5)
C['toga_border'] = frame('toga_border', 2.2, 0.2, 1.8, 'IDLE (decoy for the drumming): straightens the purple border of his toga.')
C['votes'] = frame('votes', 2.4, 0.22, 2.0, 'TELL: a slow, private smile, like a man counting votes.')
C['suspicion'] = frame('suspicion', 2.2, 0.2, 1.8, 'IDLE (decoy for the smile): glances round the table with suspicion.')
C['dictate'] = frame('dictate', 2.4, 0.2, 2.0, 'IDLE: dictates something to no one, one finger raised.', lead=-0.3)
C['appraise'] = frame('appraise', 2.2, 0.2, 1.8, 'IDLE: a cool, appraising look at the player.')
C['arrive'] = frame('arrive', 3.0, 0.05, 2.6, 'BEAT: arrives: sits down setting the laurel wreath on his head with both hands.', lead=-1)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: one finger raised, as if dictating. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: chin up, eyes narrowed.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a thin, tight smile.')
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: a satisfied smile, drawing chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in, fingertips together, eyes level.', lead=2)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: rises, wraps his toga round him, a last look back.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.56], ['viewer', 0.18], ['down', 0.08], ['side', 0.18]]
a = {'note': "Hand-authored: Caesar's face timing and his clips (poker actions, tells beside their decoys, beats, his arrival). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'adjusts his laurel wreath': 'wreath',
              "drums his fingers on the table's edge": 'drum',
              'smiles like a man counting votes': 'votes',
              'dictates something to no one': 'dictate',
              'rubs his temple': 'temple',
              'glances round the table with suspicion': 'suspicion',
              'straightens the purple border of his toga': 'toga_border'},
     'fidgets': ['appraise', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

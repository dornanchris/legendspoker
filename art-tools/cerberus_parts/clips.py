# cerberus's clips: writes web/art/cerberus/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/cerberus_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/cerberus/'
K = ROOT + 'art-tools/cerberus_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'A paw taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A paw lifts the corner of his cards; all three heads peer down.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A paw slides a short stack forward.')
C['bet'] = frame('bet', 1.4, 0.12, 1.0, 'The middle head noses a stack forward, at once (his snap quirk).', lead=1.5)
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'The middle head noses his cards away; the others lose interest.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both paws shove the whole stack; all three heads lean in.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A paw flips his cards (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both paws drag the pot in; the heads pant, pleased.')
C['attention'] = frame('attention', 2.2, 0.15, 1.8, 'TELL: all three heads snap to attention, ears up.', lead=0.5)
C['watch'] = frame('watch', 2.4, 0.22, 2.0, 'IDLE (decoy for attention): two heads watch you, one the pot.', lead=0.3)
C['yawn'] = frame('yawn', 2.2, 0.22, 1.8, 'TELL: the left head yawns, wide.', lead=0.3)
C['asleep'] = frame('asleep', 2.8, 0.25, 2.4, 'IDLE (decoy for the yawn): the right head falls asleep on the edge.', lead=0.3)
C['growl'] = frame('growl', 2.2, 0.15, 1.8, 'TELL: the heads growl at each other, teeth bared.', lead=0.5)
C['scratch'] = frame('scratch', 2.2, 0.22, 1.8, 'IDLE (decoy for the growl): the middle head scratches behind an ear.', lead=0.5)
C['sniff'] = frame('sniff', 2.2, 0.22, 1.8, 'IDLE: the right head sniffs at something beside him.', lead=0.3)
C['pant'] = frame('pant', 2.4, 0.22, 2.0, 'IDLE: all three heads pant, content.', lead=0.3)
C['stare'] = frame('stare', 2.4, 0.22, 2.0, 'IDLE: all three heads look straight at you, still.', lead=0)
C['talk'] = frame('talk', 2.0, 0.2, 1.6, 'BEAT: the middle head growls low; the others listen. Play beside his stage directions.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: hackles up, heads low and fixed.', lead=2)
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a whine, ears flat, the heads looking away.', lead=1)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: tongues lolling, a paw drawing chips in.', lead=1.5)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: all three heads low over the table, eyes locked.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: drops down from the table and pads away, one head looking back.', lead=-2)
C['look_at_you'] = {'duration': 2.0, 'note': 'BEAT: the middle head looks straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -0.8, 'in'], [0.3, 0, 'out'], [1.6, 0], [1.7, -0.8, 'in'], [1.9, 0, 'out']]}},
                    'swaps': {'eyes': [[0.15, 'viewer'], [1.7, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.6], ['viewer', 0.15], ['down', 0.15], ['side', 0.1]]
face['gaze']['tilt'] = {'ahead': [0, 0, 0], 'down': [1.2, 0.8, 2], 'viewer': [-0.6, -1.2, 0], 'side': [-0.5, 0, 0]}
# He does not speak: his callouts are stage directions. A growl if he ever does.
face['speech']['map'] = {k: ('rest' if v in ('m', 'f', 'l') else 'growl') for k, v in face['speech']['map'].items()}
a = {'note': "Hand-authored: Cerberus's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "The face layers draw on the middle head only. rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'all three heads snap to attention': 'attention', 'the left head yawns': 'yawn',
              'the heads growl at each other': 'growl', 'the middle head scratches behind an ear': 'scratch',
              'one head falls asleep': 'asleep', 'two heads watch you; one watches the pot': 'watch',
              'the right head sniffs at the nearest robe': 'sniff'},
     'fidgets': ['pant', 'stare', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

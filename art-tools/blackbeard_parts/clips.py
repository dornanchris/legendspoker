# blackbeard's clips: writes web/art/blackbeard/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/blackbeard_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/blackbeard/'
K = ROOT + 'art-tools/blackbeard_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
rose = json.load(open(ROOT + 'web/art/roosevelt/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'A knuckle raps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards, eyes down (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Slams a tall stack down well forward.', lead=3)
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Flings his cards away.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Shoves his whole stack in, grinning.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Rakes the pot in with both hands.')
C['stroke'] = frame('stroke', 2.4, 0.25, 2.0, 'TELL: strokes his braided beard.', lead=1)
C['ribbon'] = frame('ribbon', 2.2, 0.22, 1.8, 'IDLE (decoy for the stroke): twists a braid ribbon.', lead=1)
C['still'] = frame('still', 2.6, 0.3, 2.2, 'TELL: goes very still.', lead=0.3)
C['stare'] = frame('stare', 2.4, 0.25, 2.0, 'IDLE (decoy for the stillness): stares down the nearest man.', lead=1)
C['smoulder'] = frame('smoulder', 2.4, 0.22, 2.0, 'TELL: the slow-matches under his hat smoulder brighter.', lead=0.5)
C['smoke'] = frame('smoke', 2.0, 0.22, 1.6, 'IDLE (decoy for the smoulder): the matches smoke as usual.', lead=0.5)
C['pistol_down'] = frame('pistol_down', 2.2, 0.22, 1.8, 'IDLE: sets a pistol on the table.')
C['pistol_up'] = frame('pistol_up', 2.0, 0.22, 1.6, 'IDLE: picks the pistol up again, tucking it away.')
C['laugh'] = frame('laugh', 1.8, 0.15, 1.4, 'IDLE: laughs too loud, a fist on the table.', lead=2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a finger jabbing the air. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: a slow, dangerous grin.')
C['lost_pot'] = frame('lost_pot', 2.0, 0.15, 1.6, 'BEAT: lost a pot: a roar, both fists up.', lead=-2)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: arms flung wide, laughing.', lead=-1)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both fists, smoke round his face.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: sweeps off his hat in a mocking bow.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(rose['face']))
face['gaze']['idle'] = [['ahead', 0.62], ['down', 0.16], ['viewer', 0.12], ['side', 0.1]]
face['gaze']['tilt'].pop('up', None)
face['gaze']['tilt']['narrow'] = [0.8, 0, 0.5]
face['gaze']['tilt']['side'] = [-0.6, 0, 0]
a = {'note': "Hand-authored: Blackbeard's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'strokes his braided beard': 'stroke', 'goes very still': 'still',
              'the slow-matches under his hat smoulder brighter': 'smoulder', 'the fuses in his beard smoke': 'smoke',
              'sets a pistol on the table, then picks it up again': 'pistol_down', 'laughs too loud': 'laugh',
              'stares down the nearest man': 'stare'},
     'fidgets': ['ribbon', 'pistol_up', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

# leonidas's clips: writes web/art/leonidas/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/leonidas_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/leonidas/'
K = ROOT + 'art-tools/leonidas_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
rose = json.load(open(ROOT + 'web/art/roosevelt/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One knuckle raps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards, eyes down (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.6, 0.2, 1.2, 'Plants a tall stack well forward.')
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Flicks his cards away with the back of his hand.')
C['all_in'] = frame('all_in', 2.0, 0.22, 1.6, 'Shoves his whole stack in, jaw set.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Draws the pot in with both hands.')
C['fists'] = frame('fists', 2.2, 0.25, 1.8, 'TELL: plants both fists on the table.', lead=2)
C['arms_folded'] = frame('arms_folded', 2.4, 0.25, 2.0, 'IDLE (decoy for the fists): folds his arms, unimpressed.', lead=-1)
C['knuckles'] = frame('knuckles', 1.8, 0.2, 1.4, 'IDLE: cracks his knuckles.')
C['chin'] = frame('chin', 2.2, 0.25, 1.8, 'TELL: lifts his chin, looking down his nose.', lead=-1)
C['disdain'] = frame('disdain', 2.2, 0.25, 1.8, 'IDLE (decoy for the chin): a glance across the table with open disdain.', lead=1)
C['exhale'] = frame('exhale', 1.8, 0.2, 1.4, 'TELL: a hard breath out through his nose.', lead=1)
C['breathe_in'] = frame('breathe_in', 2.2, 0.25, 1.8, 'IDLE (decoy for the breath out): a slow breath in.', lead=-1)
C['cloak'] = frame('cloak', 2.0, 0.22, 1.6, 'IDLE: tugs his red cloak straight.')
C['helmet'] = frame('helmet', 2.0, 0.22, 1.6, 'IDLE: sets his crested helmet an inch to the left.')
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: one finger up, a short word. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: eyes narrowed, unimpressed.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.25, 1.8, 'BEAT: lost a pot: jaw clenched, staring at the felt.')
C['won_pot'] = frame('won_pot', 1.8, 0.2, 1.4, 'BEAT: won a pot: one curt nod.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both fists.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: lifts his helmet to put it on, keeping his appointment.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(rose['face']))
face['gaze']['idle'] = [['ahead', 0.62], ['down', 0.16], ['viewer', 0.12], ['side', 0.1]]
face['gaze']['tilt'].pop('up', None)
face['gaze']['tilt']['side'] = [-0.6, 0, 0]
a = {'note': "Hand-authored: Leonidas's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'plants both fists on the table': 'fists', 'lifts his chin': 'chin', 'exhales hard through his nose': 'exhale',
              'tugs his red cloak straight': 'cloak', 'glances across the table with open disdain': 'disdain',
              'sets his crested helmet an inch to the left': 'helmet', 'cracks his knuckles': 'knuckles'},
     'fidgets': ['arms_folded', 'breathe_in', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

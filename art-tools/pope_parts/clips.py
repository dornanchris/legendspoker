# pope's clips: writes web/art/pope/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/pope_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/pope/'
K = ROOT + 'art-tools/pope_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One finger taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of his cards (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward, graciously.')
C['bet'] = frame('bet', 1.6, 0.15, 1.2, 'Sets a stack down: a magnanimous gesture.', lead=1.5)
C['fold'] = frame('fold', 1.4, 0.18, 1.0, 'Lays his cards down with a small sigh.')
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push his whole stack in, beaming.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns his cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Both arms gather the pot.')
C['turn_ring'] = frame('turn_ring', 2.4, 0.22, 2.0, 'TELL: turns the ring on his finger.', lead=0.5)
C['admire_ring'] = frame('admire_ring', 2.2, 0.2, 1.8, 'IDLE (decoy for the ring turned): admires his own ring, hand raised.', lead=-0.3)
C['smooth_robes'] = frame('smooth_robes', 2.4, 0.22, 2.0, 'TELL: smooths his robes, unhurried.', lead=0.3)
C['mitre'] = frame('mitre', 2.2, 0.2, 1.8, 'IDLE (decoy for the robes): adjusts his mitre.', lead=-0.5)
C['hands_in_lap'] = frame('hands_in_lap', 2.8, 0.25, 2.4, 'TELL: folds his hands in his lap: they leave the table.', lead=-0.5)
C['latin'] = frame('latin', 2.4, 0.22, 2.0, 'IDLE (decoy for the hands in his lap): murmurs something in Latin, eyes half closed.')
C['benevolent'] = frame('benevolent', 2.2, 0.2, 1.8, 'IDLE: smiles benevolently at the whole table.')
C['chuckle'] = frame('chuckle', 1.8, 0.15, 1.4, 'IDLE: a quiet chuckle, one hand on his belly.', lead=-0.3)
C['fingertips'] = frame('fingertips', 2.8, 0.25, 2.4, 'IDLE: fingertips together, considering.', lead=0.5)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: one hand open, persuasive. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: eyebrows raised, a patient smile.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: a pained smile, a hand to his chest.', lead=-0.3)
C['won_pot'] = frame('won_pot', 2.2, 0.2, 1.8, 'BEAT: won a pot: beaming, gathering the chips in.', lead=2)
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in, fingertips together.', lead=2)
C['knocked_out'] = frame('knocked_out', 2.8, 0.3, 2.5, 'BEAT: knocked out: rises, gathers his robes, a gracious nod.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(kidd['face']))
face['gaze']['idle'] = [['ahead', 0.56], ['viewer', 0.22], ['down', 0.1], ['side', 0.12]]
a = {'note': "Hand-authored: the Pope's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'smooths his robes, unhurried': 'smooth_robes',
              'turns the ring on his finger': 'turn_ring',
              'folds his hands in his lap': 'hands_in_lap',
              'murmurs something in Latin': 'latin',
              'adjusts his mitre': 'mitre',
              'admires his own ring': 'admire_ring',
              'smiles benevolently at the whole table': 'benevolent'},
     'fidgets': ['chuckle', 'fingertips', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

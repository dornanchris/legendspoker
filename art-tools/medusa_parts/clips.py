# medusa's clips: writes web/art/medusa/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/medusa_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/medusa/'
K = ROOT + 'art-tools/medusa_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
rose = json.load(open(ROOT + 'web/art/roosevelt/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'Two fingertips tap the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'Lifts the corner of her cards, eyes down (the game draws the cards).')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'Slides a short stack forward (chips drawn in the hand).')
C['bet'] = frame('bet', 1.6, 0.2, 1.2, 'Sets a taller stack down well forward.')
C['fold'] = frame('fold', 1.2, 0.16, 0.8, 'Slides her cards away.')
C['all_in'] = frame('all_in', 2.0, 0.22, 1.6, 'Pushes her whole stack in, calm.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'Turns her cards over (the game draws them face up).')
C['collect'] = frame('collect', 1.8, 0.2, 1.4, 'Draws the pot in with both hands.')
C['still'] = frame('still', 2.4, 0.25, 2.0, 'TELL: the snakes in her hair go still, all looking one way.', lead=0.5)
C['drowse'] = frame('drowse', 2.4, 0.25, 2.0, 'IDLE (decoy for the stillness): the snakes drowse on her shoulders.', lead=0.5)
C['hiss'] = frame('hiss', 2.0, 0.2, 1.6, 'TELL: the snakes coil and hiss.', lead=1)
C['knot'] = frame('knot', 2.2, 0.22, 1.8, 'IDLE (decoy for the hissing): two snakes knot themselves together.', lead=0.5)
C['gaze_down'] = frame('gaze_down', 2.2, 0.25, 1.8, 'TELL: lowers her gaze to the table.', lead=0.5)
C['tuck'] = frame('tuck', 2.2, 0.22, 1.8, 'IDLE (decoy for the lowered gaze): tucks a snake behind her ear, eyes down.')
C['taste'] = frame('taste', 2.0, 0.22, 1.6, 'IDLE: one snake tastes the air.', lead=0.5)
C['nip'] = frame('nip', 2.0, 0.22, 1.6, 'IDLE: one snake nips another; she glances up at them.', lead=0.5)
C['chin'] = frame('chin', 2.6, 0.25, 2.2, 'IDLE: chin on her hand, watching the table.')
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: a quiet point, palm up. Play beside a spoken line.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: a slow, level look, the snakes rising.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.25, 1.8, 'BEAT: lost a pot: a small tired breath, the snakes sagging.')
C['won_pot'] = frame('won_pot', 2.0, 0.22, 1.6, 'BEAT: won a pot: a faint smile, the snakes swaying.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in, the snakes all forward.', lead=3)
C['knocked_out'] = frame('knocked_out', 2.6, 0.3, 2.3, 'BEAT: knocked out: draws her himation round her, the snakes settling.', lead=-2)
C['look_at_you'] = {'duration': 2.4, 'note': 'BEAT: turns to look straight at the player.',
                    'tracks': {'head': {'rot': [[0, 0], [0.2, -1, 'in'], [0.3, 0, 'out'], [1.9, 0], [2.0, -1, 'in'], [2.2, 0, 'out']]}},
                    'swaps': {'head': [[0.24, 'viewer'], [2.0, N]], 'eyes': [[0.14, 'half'], [0.24, N], [2.0, 'half'], [2.1, N]]}}
face = json.loads(json.dumps(rose['face']))
face['gaze']['tilt'].pop('narrow', None)
face['gaze']['tilt']['level'] = [0, 0, 0]
a = {'note': "Hand-authored: Medusa's face timing and his clips (poker actions, tells beside their decoys, beats). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'the snakes in her hair go still': 'still', 'the snakes in her hair coil and hiss': 'hiss',
              'lowers her gaze to the table': 'gaze_down', 'one snake tastes the air': 'taste',
              'two snakes knot themselves together': 'knot', 'one snake nips another': 'nip',
              'she tucks a snake behind her ear': 'tuck'},
     'fidgets': ['drowse', 'chin', 'look_at_you']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')

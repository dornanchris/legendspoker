# The Grey's clips: writes web/art/grey_alien/anim.json (face timing, clips, tell cues,
# fidgets) and the reference crops beside it. Run after pose_rig.py:
#   python3 art-tools/grey_alien_parts/clips.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
import json
from PIL import Image
R = ROOT + 'web/art/grey_alien/'
K = ROOT + 'art-tools/grey_alien_parts/'
rig = json.load(open(R + 'rig.json')); spec = json.load(open(K + 'pose_rig.json'))
kidd = json.load(open(ROOT + 'web/art/kidd/anim.json'))
N = None
BODY = ['torso', 'torso_over', 'arm_near', 'arm_far', 'upper_near', 'upper_far']
def frame(name, dur, t_in, t_out, note, lead=1.5):
    sw = {s: [[t_in, '-'], [t_out, N]] for s in BODY}
    sw['frame'] = [[t_in, name], [t_out, N]]
    sw['head'] = [[t_in, '-'], [t_out, N]]
    assert rig['frames'][name] is None
    tracks = {'torso': {'y': [[0, 0], [t_in, lead, 'in'], [t_in + 0.12, 0, 'out'], [t_out, 0],
                              [t_out + 0.02, lead, 'hold'], [min(dur, t_out + 0.3), 0, 'inOut']]}}
    return {'duration': dur, 'note': note, 'tracks': tracks, 'swaps': sw}
C = {}
C['check'] = frame('check', 1.2, 0.15, 0.85, 'One long finger taps the felt.')
C['peek'] = frame('peek', 1.6, 0.18, 1.25, 'A long hand cupped low over its cards, head tipped down.')
C['call'] = frame('call', 1.5, 0.18, 1.15, 'A flat hand slides forward along the felt (the chips are the game\'s).')
C['bet'] = frame('bet', 1.5, 0.15, 1.1, 'Leans in, a hand pushed well forward, unhurried.', lead=1.5)
C['all_in'] = frame('all_in', 2.0, 0.2, 1.6, 'Both hands push forward together, the head lowered, intent.', lead=3)
C['show'] = frame('show', 1.8, 0.2, 1.4, 'A hand turns palm up (the game turns the cards).')
C['fold'] = frame('fold', 1.3, 0.18, 0.9, 'The hand lifts and turns palm up, letting something go.')
C['win_big'] = frame('win_big', 2.4, 0.2, 2.0, 'BEAT: a big pot won: thin arms raised and spread; its face does not change.', lead=-2)
C['talk'] = frame('talk', 2.2, 0.22, 1.8, 'BEAT: talking without a mouth: a hand raised, a glow in its eyes.')
C['big_bet'] = frame('big_bet', 2.2, 0.25, 1.8, 'BEAT: facing a big bet: very still and upright.')
C['lost_pot'] = frame('lost_pot', 2.2, 0.2, 1.8, 'BEAT: lost a pot: its head tilts slowly, puzzled.')
C['lose_big'] = frame('lose_big', 2.6, 0.2, 2.2, 'BEAT: a crushing loss: both long hands over its great head, bowed.')
C['heads_up'] = frame('heads_up', 2.6, 0.3, 2.2, 'BEAT: down to two: leaning in on both forearms, eyes on you.', lead=3)
C['nod'] = frame('nod', 2.0, 0.25, 1.6, 'BEAT: a slow, deep nod.', lead=0)
C['membrane'] = frame('membrane', 2.4, 0.22, 2.0, 'TELL: it blinks sideways, a membrane across its eyes.', lead=0)
C['stare'] = frame('stare', 2.4, 0.22, 2.0, 'IDLE (decoy for the membrane): stares at the backs of your cards.', lead=0)
C['splay'] = frame('splay', 2.4, 0.22, 2.0, 'TELL: its long fingers splay on the table.')
C['wood'] = frame('wood', 2.4, 0.22, 2.0, 'IDLE (decoy for the splay): touches the table as if it had never seen wood.')
C['tilt'] = frame('tilt', 2.4, 0.22, 2.0, 'TELL: its head tilts forty degrees.', lead=0)
C['breathe'] = frame('breathe', 2.4, 0.22, 2.0, 'IDLE (decoy for the tilt): watches someone breathe, with interest.', lead=0)
C['hum'] = frame('hum', 2.4, 0.22, 2.0, 'IDLE: hums at a pitch you feel in your teeth (its sheet drew the membrane too: a second decoy for the blink).', lead=0)
C['turn'] = frame('turn', 2.0, 0.2, 1.6, 'IDLE: turns its head and shoulders to look at you.', lead=0)
C['fingers'] = frame('fingers', 2.4, 0.22, 2.0, 'IDLE: studies its own long fingers.')
face = json.loads(json.dumps(kidd['face']))
face['blink'] = {'every': [9, 16], 'double': 0, 'frames': [['half', 0.08], ['closed', 0.12], ['half', 0.08]]}  # rare: the membrane is its tell
face['gaze']['idle'] = [['ahead', 1]]                    # it looks by turning its head (whole frames), never its eyes
face['gaze']['tilt'] = {'ahead': [0, 0, 0]}
a = {'note': "Hand-authored: the Grey's face timing and its clips (poker actions, tells beside their decoys, beats). "
             "It has no mouth to move: speech is a glow in its eyes (eyes.py). "
             "rig.json and the images beside it are generated by art-tools/pose_rig.py.",
     'face': face, 'clips': C,
     'cues': {'blinks sideways': 'membrane', 'its head tilts forty degrees': 'tilt',
              'its long fingers splay on the table': 'splay', 'stares at the backs of your cards': 'stare',
              'hums at a pitch you feel in your teeth': 'hum', 'touches the table as if it had never seen wood': 'wood',
              'watches someone breathe, with interest': 'breathe'},
     'fidgets': ['turn', 'fingers']}
ref = {'rest': 'ref_rest.png'}
pose_of = {n: f['pose'] for n, f in spec['frames'].items()}; pose_of['rest'] = 'A1'
for clip, pose in pose_of.items():
    p = spec['poses'][pose]; x, y, w, h = p['box']
    Image.open(K + spec['sheets'][p['sheet']]).convert('RGB').crop((x, y, x + w, y + h)).save(R + f'ref_{clip}.png')
    ref[clip] = f'ref_{clip}.png'
a['reference'] = ref
json.dump(a, open(R + 'anim.json', 'w'), indent=1)
print(len(C), 'clips')
